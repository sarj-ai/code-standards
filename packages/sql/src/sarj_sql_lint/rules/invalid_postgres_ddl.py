_NON_PRODUCTION = frozenset(
    {"test", "tests", "testing", "__tests__", "fixtures", "__fixtures__", "generated", "mysql", "sqlite", "d1"}
)
_NON_UNIQUE_METHODS = frozenset({"hash", "gist", "spgist", "gin", "brin"})
_SINGLE_KEY_METHODS = frozenset({"hash", "spgist"})
_NON_NEWLINE = re.compile(r"[^\r\n]")
_SINGLE_IDENTIFIER = re.compile(POSTGRES_IDENTIFIER_PART)
_GENERATED = re.compile(r"@generated|\b(?:generated by|do not edit)\b", re.IGNORECASE)


@final
class InvalidPostgresDdl(Rule):
    id = "invalid-postgres-ddl"
    code = "SARJ126"
    documentation = RuleDocumentation(
        default_level=DefaultLevel.WARNING,
        summary="Use supported PostgreSQL index and constraint definitions.",
        rationale=(
            "Unsupported index options and constraint validation clauses fail when PostgreSQL executes a migration. "
            "These incompatibilities follow directly from the command and known built-in access-method capabilities."
        ),
        remediation=(
            "Use B-tree for a unique index; use a supported multicolumn method for multiple keys; list only column "
            "names in INCLUDE; qualify the indexed table instead of the new index name; and omit NOT VALID from "
            "UNIQUE or PRIMARY KEY additions. Preserve the intended uniqueness and query-access contract."
        ),
        category=RuleCategory.CORRECTNESS,
        autofix=AutofixPolicy.SAFE,
        limitations=(
            "Checks authored PostgreSQL SQL and the built-in PostgreSQL 18 access methods. Explicit other dialects, dumps, generated migrations, fixtures, and test sources are excluded.",
            "Only parsed CREATE INDEX definitions and direct ALTER TABLE ADD UNIQUE/PRIMARY KEY actions are inspected. Unknown access methods, unsupported syntax, column-level constraints, and procedural or dynamically executed SQL remain outside this rule.",
            "INCLUDE entries must be single identifiers; quoted column names containing punctuation remain valid. Included columns do not contribute to the key-count check.",
            "Autofix only repairs one comment-free CREATE INDEX whose explicitly qualified index name and table use the same exact PostgreSQL schema identity. It removes that index schema prefix, preserves physical lines and every other source byte, and requires one supported parsed index with identical table, basename and complete index signature. Other DDL, mismatched or unqualified schemas, multiple statements and other index errors remain manual.",
            "The repair corrects unsupported syntax from the explicit same-schema declaration; it does not claim runtime equivalence for the invalid preimage or infer table contents, installed operator classes, function volatility, referenced constraints, partition keys or deployment transaction boundaries.",
        ),
        examples=(
            RuleExample(
                example_id="same-explicit-index-schema",
                title="The table already fixes the index schema",
                outcome=ExampleOutcome.MATCH,
                scenario="same-explicit-index-schema",
                files=(
                    ExampleFile.sql(
                        "migrations/001_index.sql",
                        "CREATE INDEX app.item_key ON app.item(id);\n",
                    ),
                ),
                fixed_files=(
                    ExampleFile.sql(
                        "migrations/001_index.sql",
                        "CREATE INDEX item_key ON app.item(id);\n",
                    ),
                ),
                focus_path=PurePosixPath("migrations/001_index.sql"),
                expected_count=1,
                public=True,
            ),
            RuleExample(
                example_id="fixed-explicit-index-schema",
                title="The table supplies the schema of its index",
                outcome=ExampleOutcome.NO_MATCH,
                scenario="same-explicit-index-schema",
                files=(
                    ExampleFile.sql(
                        "migrations/001_index.sql",
                        "CREATE INDEX item_key ON app.item(id);\n",
                    ),
                ),
                focus_path=PurePosixPath("migrations/001_index.sql"),
                expected_count=0,
                public=True,
            ),
            RuleExample(
                example_id="unsupported-unique-hash",
                title="A built-in hash index cannot enforce uniqueness",
                outcome=ExampleOutcome.MATCH,
                files=(
                    ExampleFile.sql(
                        "migrations/001_index.sql", "CREATE UNIQUE INDEX item_key ON item USING hash (id);\n"
                    ),
                ),
                focus_path=PurePosixPath("migrations/001_index.sql"),
                expected_count=1,
                public=True,
            ),
            RuleExample(
                example_id="supported-unique-btree",
                title="A B-tree index supports uniqueness and included columns",
                outcome=ExampleOutcome.NO_MATCH,
                files=(
                    ExampleFile.sql(
                        "migrations/001_index.sql",
                        "CREATE UNIQUE INDEX item_key ON app.item USING btree (id) INCLUDE (label);\n",
                    ),
                ),
                focus_path=PurePosixPath("migrations/001_index.sql"),
                expected_count=0,
                public=True,
            ),
        ),
    )
    description = documentation.summary

    @override
    def check(self, path: Path, source: str) -> list[Diagnostic]:
        if (
            {part.casefold() for part in path.parts} & _NON_PRODUCTION
            or declared_dialect(source) not in {None, "postgresql"}
            or not is_postgres(source)
        ):
            return []
        if (
            is_dump_file(source, path)
            or is_generated_migration(path, source)
            or path.name.lower().endswith(".generated.sql")
            or has_file_comment_match(source, _GENERATED, limit=1024)
        ):
            return []
        findings: list[Diagnostic] = []
        for index in parse_indexes(source):
            problems = _index_problems(index)
            if problems:
                findings.append(
                    Diagnostic(
                        path,
                        index.line,
                        index.column,
                        self.code,
                        " ".join(problems),
                        DefaultLevel.WARNING,
                    )
                )
        findings.extend(
            Diagnostic(
                path,
                location.line,
                location.column,
                self.code,
                "NOT VALID is unsupported for UNIQUE and PRIMARY KEY constraints; preserve the key contract "
                "and use a supported index-backed installation when needed.",
                DefaultLevel.WARNING,
            )
            for location in _invalid_constraints(source)
        )
        return sorted(findings, key=lambda finding: (finding.line, finding.col))


def _index_problems(index: IndexDefinition) -> list[str]:
    problems: list[str] = []
    if index.unique and index.method in _NON_UNIQUE_METHODS:
        problems.append("This built-in access method cannot create a UNIQUE index; use B-tree to preserve uniqueness.")
    if index.method in _SINGLE_KEY_METHODS and len(index.keys) > 1:
        problems.append(
            "This built-in access method supports one key column; choose a multicolumn method for these keys."
        )
    if any(not _single_identifier(column) for column in index.include):
        problems.append("INCLUDE accepts column names only; move expressions to index keys or use a stored column.")
    if index.name != "<unnamed>" and not _single_identifier(index.name):
        problems.append("CREATE INDEX names cannot be schema-qualified; qualify the indexed table instead.")
    return problems


def _single_identifier(value: str) -> bool:
    return _SINGLE_IDENTIFIER.fullmatch(value) is not None


def _invalid_constraints(source: str) -> Iterator[SourceLocation]:
    masked_chars = list(mask_sql_literals_and_comments(source, mask_dollar_literals=True))
    for start, end in dollar_quoted_spans(source):
        masked_chars[start:end] = _NON_NEWLINE.sub(" ", source[start:end])
    for statement in split_statements("".join(masked_chars)):
        text = "\n".join(fragment.text for fragment in statement)
        tokens = tokenize(text)
        altered = table_actions(tokens) if tokens else None
        if altered is None:
            continue
        for action in altered[1]:
            if _invalid_constraint_validation(action):
                yield locate(statement, action[0].start)


def _invalid_constraint_validation(action: list[Token]) -> bool:
    if not consume(action, 0, "ADD"):
        return False
    cursor = 1
    if consume(action, cursor, "CONSTRAINT"):
        named = identifier(action, cursor + 1)
        if named is None or len(named[0]) != 1:
            return False
        cursor = named[1]
    if not consume(action, cursor, "UNIQUE") and not sequence(action, cursor, ("PRIMARY", "KEY")):
        return False
    top = top_level_tokens(action)
    return any(sequence(top, index, ("NOT", "VALID")) for index in range(len(top)))
