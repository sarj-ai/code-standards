from __future__ import annotations

from pathlib import Path

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_sql_lint.__main__ import analyze, main
from sarj_sql_lint.autofix import fix_source
from sarj_sql_lint.rule_base import DefaultLevel
from sarj_sql_lint.rules.no_redundant_nullability import NoRedundantNullability


P = Path("migrations/001_item.sql")
R = NoRedundantNullability()


def test_documented_examples() -> None:
    verify_native_rule(NoRedundantNullability, analyze)


@pytest.mark.parametrize(
    ("source", "expected"),
    [
        ("CREATE TABLE item (note TEXT NULL);", "CREATE TABLE item (note TEXT);"),
        ("CREATE TABLE item (a TEXT NULL, b UUID NULL);", "CREATE TABLE item (a TEXT, b UUID);"),
        ("ALTER TABLE item ADD COLUMN note TEXT NULL;", "ALTER TABLE item ADD COLUMN note TEXT;"),
        ("ALTER TABLE item ADD note JSONB NULL;", "ALTER TABLE item ADD note JSONB;"),
        ("CREATE TABLE item (note TEXT DEFAULT NULL NULL);", "CREATE TABLE item (note TEXT DEFAULT NULL);"),
        (
            "CREATE TABLE item (note TEXT NULL CHECK (note IS NULL));",
            "CREATE TABLE item (note TEXT CHECK (note IS NULL));",
        ),
        ('CREATE TABLE item ("NULL" TEXT null);', 'CREATE TABLE item ("NULL" TEXT);'),
        ("CREATE TABLE item (note TEXT /* optional */ NULL);", "CREATE TABLE item (note TEXT /* optional */);"),
    ],
)
def test_plain_nullability_is_removed_and_converges(source: str, expected: str) -> None:
    findings = R.check(P, source)
    assert findings
    assert all(item.severity is DefaultLevel.WARNING for item in findings)
    assert fix_source(P, source, rule_ids=[R.id]) == expected
    assert not R.check(P, expected)
    assert fix_source(P, expected, rule_ids=[R.id]) == expected


@pytest.mark.parametrize("declaration", ["INTEGER NOT NULL PRIMARY KEY", "INTEGER PRIMARY KEY NOT NULL"])
def test_primary_key_nullability_is_reported_for_manual_catalog_review(declaration: str) -> None:
    source = f"CREATE TABLE item (id {declaration});"
    findings = R.check(P, source)
    assert len(findings) == 1
    assert "PRIMARY KEY" in findings[0].message
    assert fix_source(P, source, rule_ids=[R.id]) == source


@pytest.mark.parametrize(
    "source",
    [
        "CREATE TABLE item (id INTEGER PRIMARY KEY, note TEXT);",
        "CREATE TABLE item (note TEXT NOT NULL);",
        "CREATE TABLE item (note TEXT DEFAULT NULL);",
        "CREATE TABLE item (note TEXT CHECK (note IS NOT NULL));",
        "CREATE TABLE item (note TEXT CONSTRAINT optional NULL);",
        "CREATE TABLE item (id INTEGER CONSTRAINT required NOT NULL PRIMARY KEY);",
        "CREATE TABLE item (id INTEGER NOT NULL, PRIMARY KEY (id));",
        "CREATE TABLE item (id SERIAL NULL);",
        "CREATE TABLE item (id INTEGER GENERATED ALWAYS AS IDENTITY NULL);",
        "CREATE TABLE item (a INTEGER, b INTEGER GENERATED ALWAYS AS (a * 2) STORED NULL);",
        "CREATE TABLE item (id INTEGER NULL PRIMARY KEY);",
        "CREATE TABLE item (note TEXT NULL NOT NULL);",
        "CREATE TABLE item (note TEXT NULL NULL);",
        "CREATE TABLE item (note TEXT NULL;",
        "SELECT 'CREATE TABLE item (note TEXT NULL);';",
        "-- CREATE TABLE item (note TEXT NULL);\nSELECT 1;",
        "DO $$ BEGIN CREATE TABLE item (note TEXT NULL); END $$;",
        "CREATE VIEW example AS SELECT NULL AS value;",
        "ALTER TABLE item ALTER COLUMN note DROP NOT NULL;",
        "COPY item FROM STDIN;\nCREATE TABLE item (note TEXT NULL);\n\\.\n",
    ],
)
def test_nonredundant_named_implicit_and_unsupported_contracts_remain_unchanged(source: str) -> None:
    assert R.check(P, source) == []
    assert fix_source(P, source, rule_ids=[R.id]) == source


@pytest.mark.parametrize("ending", ["\n", "\r\n", "\r"])
def test_physical_locations_and_endings_are_preserved(ending: str) -> None:
    source = f"-- rationale{ending}CREATE TABLE item (note TEXT NULL);{ending}"
    findings = R.check(P, source)
    assert (findings[0].line, findings[0].col) == (2, 30)
    assert fix_source(P, source, rule_ids=[R.id]) == f"-- rationale{ending}CREATE TABLE item (note TEXT);{ending}"


def test_own_line_nullability_requires_manual_layout_review() -> None:
    source = "CREATE TABLE item (note TEXT\n  NULL);"
    assert len(R.check(P, source)) == 1
    assert fix_source(P, source, rule_ids=[R.id]) == source


@pytest.mark.parametrize(
    ("path", "prefix"),
    [
        (Path("schema.sql"), ""),
        (Path("fixtures/001.sql"), ""),
        (Path("migrations/001.generated.sql"), ""),
        (P, "-- dialect: mysql\n"),
        (P, "-- generated by tool\n"),
        (P, "--> statement-breakpoint\n"),
    ],
)
def test_foreign_generated_and_fixture_sources_are_excluded(path: Path, prefix: str) -> None:
    source = f"{prefix}CREATE TABLE item (note TEXT NULL);"
    assert R.check(path, source) == []
    assert fix_source(path, source, rule_ids=[R.id]) == source


def test_selection_and_exact_suppression_are_preserved() -> None:
    source = (
        "CREATE TABLE item (note TEXT NULL); -- sarj-noqa: SARJ132 -- schema export requires explicit nullability\n"
    )
    assert fix_source(P, source, rule_ids=[R.id]) == source
    assert fix_source(P, "CREATE TABLE item (note TEXT NULL);", rule_ids=[]) == "CREATE TABLE item (note TEXT NULL);"


def test_nullable_additions_converge_with_existing_guard_and_combination_fixes() -> None:
    source = "-- migrate:up\nALTER TABLE item ADD COLUMN a TEXT NULL;\nALTER TABLE item ADD COLUMN b TEXT NULL;\n"
    fixed = fix_source(P, source)
    assert (
        fixed
        == "-- migrate:up\nALTER TABLE item ADD COLUMN IF NOT EXISTS a TEXT,\n    ADD COLUMN IF NOT EXISTS b TEXT;\n"
    )
    assert fix_source(P, fixed) == fixed


def test_cli_reports_warning_and_fixes_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    path = tmp_path / "001.sql"
    path.write_text("CREATE TABLE item (note TEXT NULL);\n")
    assert main(["check", "--rule", R.id, str(path)]) == 0
    assert "SARJ132" in capsys.readouterr().out
    assert main(["check", "--rule", R.id, "--fix", str(path)]) == 0
    assert path.read_text() == "CREATE TABLE item (note TEXT);\n"
    assert not capsys.readouterr().out
