from __future__ import annotations

from pathlib import Path

import pytest

from sarj_iac_lint.__main__ import main
from sarj_iac_lint._hcl import tokens
from sarj_iac_lint.autofix import fix_source


@pytest.mark.parametrize(
    ("source", "expected"),
    [
        ('# ==== Network ====\r\nlocals { snow = "☃" }\r\n', '\r\nlocals { snow = "☃" }\r\n'),
        (
            'locals {\n  # Set instance type\n  instance_type = "small"\n}\n',
            'locals {\n\n  instance_type = "small"\n}\n',
        ),
        (
            'locals {\n  /* Set instance type */\n  instance_type = "small"\n}\n',
            'locals {\n\n  instance_type = "small"\n}\n',
        ),
        (
            '# resource "google_storage_bucket" "old" {\n# name = "old"\n# }\nlocals { a = 1 }\n',
            "\n\n\nlocals { a = 1 }\n",
        ),
    ],
)
def test_comment_fixes_preserve_tokens_and_converge(source: str, expected: str) -> None:
    path = Path("main.tf")
    fixed = fix_source(path, source)
    assert fixed == expected
    assert tokens(fixed) == tokens(source)
    assert fix_source(path, fixed) == fixed


def test_tautological_validation_is_removed_without_touching_domain_validation() -> None:
    source = (
        'variable "region" {\n  type = string\n'
        '  validation {\n    condition = can(tostring(var.region))\n    error_message = "Must be string."\n  }\n'
        '  validation {\n    condition = length(var.region) > 0\n    error_message = "Required."\n  }\n}\n'
    )
    expected = source.replace(
        '  validation {\n    condition = can(tostring(var.region))\n    error_message = "Must be string."\n  }\n',
        "\n\n\n\n",
    )
    fixed = fix_source(Path("variables.tf"), source)
    assert fixed == expected
    assert fix_source(Path("variables.tf"), fixed) == fixed


@pytest.mark.parametrize(
    "source",
    [
        'locals {\n  # Set instance type # sarj-noqa: SARJ207\n  instance_type = "small"\n}\n',
        "# Generated by tool; DO NOT EDIT\n# ==== Network ====\nlocals { a = 1 }\n",
        "# ==== License ====\nlocals { a = 1 }\n",
        '# ==== Network ====\nlocals { a = "unterminated\n',
        "locals {\n note = <<EOF\n# ==== Network ====\nEOF\n}\n",
        'variable "v" {\n type = string\n validation {\n condition = can(var.v)\n error_message = "${var.message}"\n }\n}\n',
        'variable "v" {\n type = string\n validation {\n # Preserve constraint rationale.\n condition = can(var.v)\n error_message = "Must be readable."\n }\n}\n',
        '# Preserve old module because retirement requires review.\n# resource "x" "old" {\n# }\nlocals { a = 1 }\n',
        'variable "v" {\n type = string\n broken =\n validation {\n condition = can(var.v)\n error_message = "Must be readable."\n }\n}\n',
        'locals {\n  # Set instance type\n    # Keep this because compatibility requires review.\n  instance_type = "small"\n}\n',
    ],
)
def test_uncertain_or_owned_hcl_is_preserved(source: str) -> None:
    assert fix_source(Path("main.tf"), source) == source


def test_disabled_rule_does_not_fix() -> None:
    source = "# ==== Network ====\nlocals { a = 1 }\n"
    assert fix_source(Path("main.tf"), source, rule_ids=[]) == source


def test_literal_true_guard_removal_preserves_resource_and_real_assertion() -> None:
    source = (
        'resource "terraform_data" "guard" {\n  input = var.value\n  lifecycle {\n'
        '    precondition {\n      condition = true\n      error_message = "Always passes."\n    }\n'
        '    precondition {\n      condition = var.enabled\n      error_message = "Must be enabled."\n    }\n'
        "  }\n}\n"
    )
    fixed = fix_source(Path("main.tf"), source)
    assert fixed == source.replace(
        '    precondition {\n      condition = true\n      error_message = "Always passes."\n    }\n',
        "\n\n\n\n",
    )
    assert fix_source(Path("main.tf"), fixed) == fixed


def test_cli_fix_preserves_crlf_and_permissions(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    path = tmp_path / "main.tf"
    path.write_bytes(b"# ==== Network ====\r\nlocals { a = 1 }\r\n")
    path.chmod(0o755)
    assert main(["check", "--rule", "no-comment-cruft", "--fix", str(path)]) == 0
    assert path.read_bytes() == b"\r\nlocals { a = 1 }\r\n"
    assert path.stat().st_mode & 0o777 == 0o755
    assert not capsys.readouterr().out


@pytest.mark.parametrize(
    ("rule_id", "source", "exit_code"),
    [
        (
            "no-restated-comment",
            'locals {\n # Set instance type # sarj-noqa: SARJ207\n instance_type = "small"\n}\n',
            0,
        ),
        ("no-comment-cruft", "# ==== Network ====\nlocals { a = 1\n", 1),
        ("no-restated-comment", "# ==== Network ====\nlocals { a = 1 }\n", 0),
    ],
)
def test_cli_fix_respects_suppression_selection_and_malformed_source(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], rule_id: str, source: str, exit_code: int
) -> None:
    path = tmp_path / "main.tf"
    path.write_bytes(source.encode())
    assert main(["check", "--rule", rule_id, "--fix", str(path)]) == exit_code
    assert path.read_bytes() == source.encode()
    capsys.readouterr()


def test_cli_fix_refuses_symlink(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    path = tmp_path / "main.tf"
    source = b"# ==== Network ====\nlocals { a = 1 }\n"
    path.write_bytes(source)
    link = tmp_path / "linked.tf"
    link.symlink_to(path)
    assert main(["check", "--rule", "no-comment-cruft", "--fix", str(link)]) == 2
    assert path.read_bytes() == source
    assert link.is_symlink()
    assert "symlink" in capsys.readouterr().err
