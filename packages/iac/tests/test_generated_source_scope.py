from __future__ import annotations

from typing import TYPE_CHECKING

import pytest

from sarj_iac_lint.__main__ import analyze
from sarj_iac_lint._hcl import header_comment_lines
from sarj_iac_lint.rules import REGISTRY


if TYPE_CHECKING:
    from pathlib import Path


_RULES = (
    "no-comment-cruft",
    "no-environment-conditional",
    "no-dead-environment-input",
    "no-restated-comment",
    "no-redundant-variable-validation",
)
_HEADER_FORMS = (
    ("# Code generated by fixture writer. Do not edit.\n", 0),
    ("/* Code generated by fixture writer. Do not edit. */\n", 0),
    ("/*\n * Code generated by fixture writer. Do not edit.\n */\n", 0),
    ("\n" * 19 + "# Code generated by fixture writer. Do not edit.\n", 0),
    ("\n" * 20 + "# Code generated by fixture writer. Do not edit.\n", 1),
    ("# Code generated by fixture writer.\n", 1),
)


@pytest.mark.parametrize("rule", _RULES)
@pytest.mark.parametrize(("prefix", "expected"), _HEADER_FORMS)
@pytest.mark.parametrize("crlf", [False, True])
def test_generated_headers_preserve_rule_scope(
    rule: str, prefix: str, expected: int, tmp_path: Path, *, crlf: bool
) -> None:
    _check_fixture(rule, prefix + "\n", expected, tmp_path, crlf=crlf)


@pytest.mark.parametrize("rule", _RULES)
@pytest.mark.parametrize("crlf", [False, True])
def test_generated_text_in_hcl_values_does_not_hide_findings(rule: str, tmp_path: Path, *, crlf: bool) -> None:
    if rule == "no-dead-environment-input":
        files = {
            "variables.tf": 'variable "retained_feature" { type = bool }\n',
            "env/dev/terraform.tfvars": (
                "removed_feature = <<DOC\n# Code generated by fixture writer. Do not edit.\nDOC\n"
            ),
        }
        paths: list[Path] = []
        for name, raw_source in files.items():
            path = tmp_path / name
            path.parent.mkdir(parents=True, exist_ok=True)
            source = raw_source.replace("\n", "\r\n") if crlf else raw_source
            path.write_bytes(source.encode())
            paths.append(path)
        assert len(analyze([rule], paths)) == 1
        return
    prefix = (
        "locals {\n public_note = <<DOC\n# Code generated by fixture writer. Do not edit.\nDOC\n}\n"
        if rule in {"no-comment-cruft", "no-environment-conditional"}
        else '/* ordinary header */ locals { public_note = "Code generated by fixture writer. Do not edit." }\n'
    )
    _check_fixture(rule, prefix, 1, tmp_path, crlf=crlf)


def _check_fixture(rule: str, prefix: str, expected: int, tmp_path: Path, *, crlf: bool) -> None:
    if rule == "no-dead-environment-input":
        files = {
            "variables.tf": 'variable "retained_feature" { type = bool }\n',
            "env/dev/terraform.tfvars": "removed_feature = true\n",
        }
        focus = "env/dev/terraform.tfvars"
    else:
        spec = REGISTRY[rule].native_spec()
        assert spec is not None
        example = next(
            example
            for example in spec.examples
            if str(example.outcome) == "match" and str(example.focus_path).endswith(".tf")
        )
        files = {str(file.path): file.source for file in example.files}
        focus = str(example.focus_path)
    paths: list[Path] = []
    for name, raw_source in files.items():
        source = (prefix if name == focus else "") + raw_source
        source = source.replace("\n", "\r\n") if crlf else source
        path = tmp_path / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(source.encode())
        paths.append(path)
    findings = analyze([rule], paths)
    assert sum(finding.path == tmp_path / focus for finding in findings) == expected
    assert findings == analyze([rule], paths)


def test_header_projection_stops_after_twenty_physical_lines() -> None:
    source = "# Code generated by fixture writer. Do not edit.\n" + "\n" * 19
    assert header_comment_lines(source + 'locals { broken = "unterminated') == (
        "# Code generated by fixture writer. Do not edit.",
    )
    assert not header_comment_lines("locals {\n value = <<DOC\n# Code generated by fixture writer. Do not edit.\n")


def test_header_projection_respects_closed_comment_and_code_boundary() -> None:
    source = '/* ordinary header */ locals { value = "generated. Do not edit." }\n# later\n'
    assert header_comment_lines(source, leading_only=True) == ("/* ordinary header */",)
    assert header_comment_lines(source) == ("/* ordinary header */", "# later")


def test_header_window_keeps_only_true_comment_prefixes() -> None:
    true_comment = "/* Code generated by fixture writer. Do not edit.\n" + "ordinary header\n" * 30 + "*/\n"
    expected = tuple(true_comment.splitlines()[:20])
    assert header_comment_lines(true_comment) == expected
    source_data = "locals {\n value = <<DOC\n" + "# Code generated by fixture writer. Do not edit.\n" * 30 + "DOC\n}\n"
    assert not header_comment_lines(source_data)
