from pathlib import Path

from sarj_iac_lint.json_boundary import JsonValue, parse_json


SCHEMA_PATH = Path(__file__).with_name("schemas") / "module-architecture.v1.schema.json"
TYPES_PATH = Path(__file__).with_name("architecture_types.py")


def annotation_schema() -> dict[str, JsonValue]:
    schema = parse_json(SCHEMA_PATH.read_text(encoding="utf-8"))
    if (
        isinstance(schema, dict)
        and isinstance(definitions := schema.get("$defs"), dict)
        and isinstance(annotation := definitions.get("annotation"), dict)
    ):
        return annotation
    message = "Missing packaged module architecture schema"
    raise ValueError(message)


def render_types() -> str:
    schema = annotation_schema()
    properties = schema["properties"]
    if not isinstance(properties, dict):
        message = "Missing annotation properties"
        raise TypeError(message)
    lines = [
        '"""Generated by python -m sarj_iac_lint.generate_architecture_types; do not edit."""',
        "",
        "from dataclasses import dataclass",
        "from enum import StrEnum",
        "",
        "",
    ]
    for field, name in (("min_view", "MinView"), ("replacement", "Replacement")):
        definition = properties[field]
        if not isinstance(definition, dict) or not isinstance(values := definition.get("enum"), list):
            message = "Missing finite annotation enum"
            raise TypeError(message)
        lines.append(f"class {name}(StrEnum):")
        for value in values:
            if not isinstance(value, str) or not value.isidentifier():
                message = "Invalid annotation enum member"
                raise ValueError(message)
            lines.append(f'    {value.upper()} = "{value}"')
        lines.extend(("", ""))
    attributes = ["    summary: str", "    min_view: MinView", "    replacement: Replacement"]
    lines.extend(("@dataclass(frozen=True, slots=True)", "class ModuleArchitecture:", *attributes, ""))
    return "\n".join(lines)


if __name__ == "__main__":
    TYPES_PATH.write_text(render_types(), encoding="utf-8")
