def test_comment_wall_removes_only_exact_diagnosed_members() -> None:
    source = (
        "# Set build name\nname: build\n"
        "# Run build command\nrun: make build\n"
        "# Set deploy image\nimage: app\n"
        "# Run deploy command\ncommand: deploy\n"
    )
    fixed = fix_source(Path("config.yaml"), source, rule_ids=["config-comment-wall"])
    assert fixed == source.replace("# Set build name", "")
    assert parse_yaml_documents(fixed) == parse_yaml_documents(source)
    assert fix_source(Path("config.yaml"), fixed, rule_ids=["config-comment-wall"]) == fixed


@pytest.mark.parametrize(("name", "separator"), [("config.toml", " = "), ("config.yaml", ": ")])
@pytest.mark.parametrize("ending", ["\n", "\r\n"])
def test_adjacent_disabled_groups_with_distinct_indentation_do_not_overlap(
    name: str, separator: str, ending: str
) -> None:
    source = ending.join(
        (
            f"# timeout{separator}30",
            f"# retries{separator}4",
            f"  # timeout{separator}40",
            f"  # retries{separator}5",
            f"timeout{separator}10",
            "",
        )
    )
    path = Path(name)
    fixed = fix_source(path, source, rule_ids=["commented-out-config"])
    assert fixed == ending * 4 + f"timeout{separator}10{ending}"
    parser = tomllib.loads if path.suffix == ".toml" else parse_yaml_documents
    assert parser(fixed) == parser(source)
    assert fix_source(path, fixed, rule_ids=["commented-out-config"]) == fixed


def test_plain_markdown_comment_with_single_line_code_and_fenced_html_is_fixable() -> None:
    source = "`inline code`\n\n```html\n<script>\n```\n\n<!--\n# Retired\n-->\n"
    expected = "`inline code`\n\n```html\n<script>\n```\n\n\n\n\n"
    fixed = fix_source(Path("README.md"), source, rule_ids=["hidden-markdown-heading"])
    assert fixed == expected
    assert fix_source(Path("README.md"), fixed, rule_ids=["hidden-markdown-heading"]) == fixed


@pytest.mark.parametrize("prefix", ["", "\ufeff", "\ufeff\n\n", "\n\n"])
def test_yaml_frontmatter_metadata_remains_byte_identical_and_converges(prefix: str) -> None:
    metadata = "description: |\n  <!--\n  # Heading payload\n  -->\n"
    source = f"{prefix}---\n{metadata}---\n# Current\n"
    fixed = fix_source(Path("README.md"), source, rule_ids=["hidden-markdown-heading"])
    assert fixed == source
    assert parse_yaml_documents(fixed.split("---\n")[1]) == parse_yaml_documents(metadata)
    assert fix_source(Path("README.md"), fixed, rule_ids=["hidden-markdown-heading"]) == fixed
