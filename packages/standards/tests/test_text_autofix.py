if TYPE_CHECKING:
    from sarj_standards.libs.linting.textlint import _MarkdownHtmlComment  # pyright: ignore[reportPrivateUsage]  # sarj-noqa: SARJ048 -- Preserve the real scanner's private immutable return type in the call-count observer without adding a test-only public API.


def _observe_comment_scans(monkeypatch: pytest.MonkeyPatch) -> list[str]:
    scanned: list[str] = []
    original = textlint._markdown_html_comments  # ruff: ignore[private-member-access]  # pyright: ignore[reportPrivateUsage] -- observe the real scan while public fix_source owns the complete behavior under test.

    def counted(source: str) -> list[_MarkdownHtmlComment]:
        scanned.append(source)
        return original(source)

    monkeypatch.setattr(  # sarj-noqa: SARJ445 -- count invocations of the real scanner without replacing its parsing or comment facts.
        textlint, "_markdown_html_comments", counted
    )
    return scanned


def test_markdown_fix_reuses_one_original_source_comment_scan(monkeypatch: pytest.MonkeyPatch) -> None:
    prefix = "Visible before\u2028visible after\r\n"
    source = prefix + "<!--\r\n## Old ☃\r\nRetired.\r\n-->\r\n# Current\r\n"
    scanned = _observe_comment_scans(monkeypatch)

    fixed = fix_source(Path("README.md"), source, rule_ids=["hidden-markdown-heading"])

    assert fixed == prefix + "\r\n" * 4 + "# Current\r\n"
    assert scanned == [source]


def test_excluded_markdown_does_not_scan_comments(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    source = "<!--\n# Retired\n-->\n"
    (tmp_path / ".sarj-standards.toml").write_text('[text]\nexclude = ["guide.md"]\n', encoding="utf-8")
    scanned = _observe_comment_scans(monkeypatch)

    fixed = fix_source(tmp_path / "guide.md", source, root=tmp_path, rule_ids=["hidden-markdown-heading"])

    assert fixed == source
    assert scanned == []


def test_generated_markdown_scans_once_and_preserves_ownership(monkeypatch: pytest.MonkeyPatch) -> None:
    source = "<!-- Generated by tool; DO NOT EDIT -->\n\n<!--\n# Retired\n-->\n"
    scanned = _observe_comment_scans(monkeypatch)

    fixed = fix_source(Path("README.md"), source, rule_ids=["hidden-markdown-heading"])

    assert fixed == source
    assert scanned == [source]


@pytest.mark.parametrize(
    ("name", "source", "expected"),
    [
        ("config.yaml", "# name is build\nname: build\n", "\nname: build\n"),
        ("config.toml", "# retries is 3\nretries = 3\n", "\nretries = 3\n"),
        ("config.yaml", "# retries: 3\n# timeout: 30\nname: build\n", "\n\nname: build\n"),
        ("README.md", "<!--\r\n## Old ☃\r\nRetired.\r\n-->\r\n# Current\r\n", "\r\n\r\n\r\n\r\n# Current\r\n"),
    ],
)
def test_text_fixes_preserve_values_and_converge(name: str, source: str, expected: str) -> None:
    path = Path(name)
    fixed = fix_source(path, source)
    assert fixed == expected
    if path.suffix == ".yaml":
        assert parse_yaml_documents(fixed) == parse_yaml_documents(source)
    elif path.suffix == ".toml":
        assert tomllib.loads(fixed) == tomllib.loads(source)
    assert fix_source(path, fixed) == fixed


