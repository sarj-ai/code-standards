def test_real_cli_formats_native_terraform_and_converges(tmp_path: Path) -> None:
    assert Standards(tmp_path).setup(configs=("yamllint",), install=False).exit_code == 0
    path = tmp_path / "main.tf"
    path.write_text("locals {answer=1+2}\n")

    assert main(["--root", str(tmp_path), "fix", str(path)]) == 0
    assert path.read_text() == "locals { answer = 1 + 2 }\n"
    original = path.read_bytes()
    assert main(["--root", str(tmp_path), "fix", str(path)]) == 0
    assert path.read_bytes() == original


@pytest.mark.parametrize("notice", ["SPDX-License-Identifier: MIT", "sarj-noqa: SARJ212 -- approved scope"])
def test_native_formatter_cannot_delete_legal_notices_or_directives(tmp_path: Path, notice: str) -> None:
    path = tmp_path / "variables.tf"
    original = f'variable /* {notice} */ "sample" {{\n  type=string\n}}\n'.encode()
    path.write_bytes(original)

    with pytest.raises(ValueError, match="would change nonempty comments"):
        autofix.fix_paths(tmp_path, [str(path)], terraform=True)

    assert path.read_bytes() == original


def test_formatter_retains_ordinary_comments_and_literal_comment_markers(tmp_path: Path) -> None:
    path = tmp_path / "main.tf"
    source = '# SPDX-License-Identifier: MIT\nlocals {\n  endpoint="https://example.invalid/#fragment"\n}\n'
    path.write_text(source)

    assert autofix.fix_paths(tmp_path, [str(path)], terraform=True) == (path,)
    assert path.read_text().startswith("# SPDX-License-Identifier: MIT\n")
    assert '"https://example.invalid/#fragment"' in path.read_text()
    assert autofix.fix_paths(tmp_path, [str(path)], terraform=True) == ()


@pytest.mark.parametrize("engine", ["core", "iac"])
def test_source_observation_refuses_even_a_literal_gate_fix(tmp_path: Path, engine: str) -> None:
    path = tmp_path / "main.tf"
    source = (
        'resource "terraform_data" "this" {\n  count = true ? 1 : 0\n}\n'
        'locals { fingerprint = filesha256("${path.module}/main.tf") }\n'
    )
    path.write_text(source)

    if engine == "core":
        with pytest.raises(ValueError, match="source-reading"):
            autofix.fix_paths(tmp_path, [str(path)])
    else:
        assert iac_main(["check", "--fix", "--rule", "conditional-resource-presence", str(path)]) == 2
    assert path.read_text() == source


