def test_formatter_is_planned_before_any_write_and_preserves_concurrent_changes(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    first = tmp_path / "a.tf"
    second = tmp_path / "b.tf"
    original = "locals {a=1}\n"
    concurrent = "locals { b = 3 }\n"
    first.write_text(original)
    second.write_text("locals {b=2}\n")
    native = external.run_process_input
    calls: list[ProcessOutput] = []

    def edit_after_native(argv: tuple[str, ...], *, cwd: Path, source: str) -> ProcessOutput:
        result = native(argv, cwd=cwd, source=source)
        calls.append(result)
        if len(calls) == 1:
            second.write_text(concurrent)
        return result

    monkeypatch.setattr(  # sarj-noqa: SARJ445 -- keep the real pinned formatter and inject only a concurrent source edit after native computation.
        terraform_format, "run_process_input", edit_after_native
    )
    with pytest.raises(OSError, match="changed"):
        autofix.fix_paths(tmp_path, [str(first), str(second)], terraform=True)

    assert first.read_text() == original
    assert second.read_text() == concurrent


def test_json_is_not_sent_to_the_native_hcl_formatter(tmp_path: Path) -> None:
    path = tmp_path / "main.tf.json"
    source = '{"locals":{"answer":3}}'
    path.write_text(source)

    assert autofix.fix_paths(tmp_path, [str(path)], terraform=True) == ()
    assert path.read_text() == source


def test_generated_provenance_requires_generator_review_before_formatting(tmp_path: Path) -> None:
    path = tmp_path / "main.tf"
    source = "# Code generated by compiler. DO NOT EDIT.\nlocals {a=1}\n"
    path.write_text(source)

    with pytest.raises(ValueError, match="generated Terraform"):
        autofix.fix_paths(tmp_path, [str(path)], terraform=True)

    assert path.read_text() == source
