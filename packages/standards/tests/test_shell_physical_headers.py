from __future__ import annotations

from typing import TYPE_CHECKING

import pytest

from sarj_standards.libs.linting import shell_format, textlint
from sarj_standards.libs.rules import EvaluationCase, ExpectedOutcome, Language, RuleProblem


if TYPE_CHECKING:
    from pathlib import Path


PROBLEM = RuleProblem(
    key="shell-physical-header-lines",
    summary="Literal separator characters inside one shell comment do not create a new header comment.",
    harm="A fake generated marker can bypass formatting, and a fake directive can select the wrong dialect.",
    languages=frozenset({Language.SHELL}),
    bad_examples=("# ordinary comment\u2028# shellcheck shell=bash\ntrue\n",),
    good_examples=("# ordinary comment\n# shellcheck shell=bash\ntrue\n",),
    exclusions=("Real LF and CRLF header lines keep their existing dialect and generated-file contracts",),
)


@pytest.mark.parametrize("separator", ["\v", "\f", "\r", "\x85", "\u2028", "\u2029"])
def test_comment_data_cannot_introduce_a_shell_directive(tmp_path: Path, separator: str) -> None:
    case = EvaluationCase(
        "literal-comment-separator",
        Language.SHELL,
        f"# ordinary comment{separator}# shellcheck shell=bash\ntrue\n",
        expected=ExpectedOutcome.NO_MATCH,
    )
    assert case.language in PROBLEM.languages
    path = tmp_path / "library.sh"
    path.write_bytes(case.source.encode())
    assert textlint.shell_dialect(path) == "sh"


@pytest.mark.parametrize("separator", ["\v", "\f", "\r", "\x85", "\u2028", "\u2029"])
def test_comment_data_cannot_introduce_a_generated_exemption(separator: str) -> None:
    case = EvaluationCase(
        "literal-generated-marker-separator",
        Language.SHELL,
        f"# ordinary comment{separator}# Gradle start up script for POSIX generated by Gradle.\ntrue\n",
        expected=ExpectedOutcome.NO_MATCH,
    )
    assert not shell_format.is_generated(case.source)


@pytest.mark.parametrize("newline", ["\n", "\r\n"])
def test_real_header_lines_keep_native_contracts(tmp_path: Path, newline: str) -> None:
    path = tmp_path / "library.sh"
    path.write_bytes(f"# ordinary comment{newline}# shellcheck shell=bash{newline}true{newline}".encode())
    assert textlint.shell_dialect(path) == "bash"
    assert shell_format.is_generated(
        f"# ordinary comment{newline}# Gradle start up script for POSIX generated by Gradle.{newline}true{newline}"
    )


def test_fake_generated_header_remains_eligible_for_native_formatting(tmp_path: Path) -> None:
    path = tmp_path / "source.sh"
    source = (
        '# ordinary comment\u2028# Gradle start up script for POSIX generated by Gradle.\nprintf  "%s\\n"   unchanged\n'
    )
    path.write_bytes(source.encode())
    reports = shell_format.analyze_sources(root=tmp_path, paths=[str(path)])
    assert len(reports) == 1
    assert [finding.rule_id for finding in reports[0].diagnostics] == ["format"]
    assert shell_format.fix_sources(tmp_path, [str(path)]) == 0
    once = path.read_bytes()
    assert b"\xe2\x80\xa8" in once
    assert shell_format.fix_sources(tmp_path, [str(path)]) == 0
    assert path.read_bytes() == once
