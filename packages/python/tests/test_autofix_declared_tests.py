from __future__ import annotations

import ast
from pathlib import Path
import subprocess
import sys

import pytest
from sarj_rule_contracts import apply_edits

from sarj_python_lint._autofix_declared_tests import fixes
from sarj_python_lint._file_context import PythonFileContext
from sarj_python_lint.autofix import fix_source
from sarj_python_lint.rules import REGISTRY


_RULE = "prefer-pytest-dependency-fixtures"
_PATH = Path("tests/test_service.py")
_SOURCE = """import pytest
from typing import Protocol

class Port(Protocol):
    def read(self) -> int: ...

class Store:
    def read(self) -> int:
        return 1

class Service:
    def __init__(self, store: Port) -> None:
        self.store = store

    def read(self) -> int:
        return self.store.read()

@pytest.fixture
def store_factory() -> type[Store]:
    return Store

def test_read(store_factory: type[Store]) -> None:
    if store_factory is Store:
        service = Service(Store())
        assert service.read() == 1
"""
_FIXED = _SOURCE.replace("Service(Store())", "Service(store_factory())")


@pytest.mark.parametrize("newline", ["\n", "\r\n"], ids=("lf", "crlf"))
def test_autofix_reuses_only_the_existing_identity_guarded_factory(newline: str) -> None:
    source, expected = (text.replace("\n", newline) for text in (_SOURCE, _FIXED))
    findings = REGISTRY[_RULE]().check(_PATH, source)
    assert len(findings) == 1
    edits = fixes(PythonFileContext(_PATH, source), findings[0])
    assert len(edits) == 1
    # Only the constructor identifier may change; the rest of the fixture graph is the oracle.
    assert apply_edits(source, edits) == expected
    assert source[edits[0].start : edits[0].end] == "Store"
    assert edits[0].replacement == "store_factory"
    assert REGISTRY[_RULE]().check(_PATH, expected) == []
    assert fix_source(_PATH, source, rule_ids=[_RULE]) == expected
    assert fix_source(_PATH, source, rule_ids=[]) == source
    assert fix_source(_PATH, expected, rule_ids=[_RULE]) == expected
    before, after = ast.parse(source), ast.parse(expected)
    before_call = next(
        node
        for node in ast.walk(before)
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "Store"
    )
    assert isinstance(before_call.func, ast.Name)
    before_call.func.id = "store_factory"
    assert ast.dump(before, include_attributes=False) == ast.dump(after, include_attributes=False)


@pytest.mark.parametrize(
    ("old", "new"),
    [
        ("if store_factory is Store:", "if store_factory == Store:"),
        ("if store_factory is Store:", "if store_factory is not Store:"),
        ("if store_factory is Store:", "assert store_factory is Store\n    if True:"),
        ("        service = Service(Store())", "        observe()\n        service = Service(Store())"),
        ("Service(Store())", "Service(store=Store())"),
        ("Service(Store())", "Service(Store(), observe())"),
        ("Service(Store())", "Service(Store(observe()))"),
        ("class Service:", "@decorate\nclass Service:"),
        ("class Service:", "class Service(metaclass=Meta):"),
        ("class Store:", "class Store(Base):"),
        ("return Store\n", "return Store()\n"),
        ("return 1\n", "return read_value()\n"),
        ("def test_read", "async def test_read"),
        ("self, store: Port", "self: observe(), store: Port"),
    ],
)
def test_autofix_refuses_unproved_factory_identity_and_evaluation_order(old: str, new: str) -> None:
    source = _SOURCE.replace(old, new)
    assert source != _SOURCE
    assert fix_source(_PATH, source, rule_ids=[_RULE]) == source


def test_autofix_preserves_suppressed_generated_and_comment_owned_tests() -> None:
    for source in (
        "# Generated by protoc. Do not edit.\n" + _SOURCE,
        _SOURCE.replace("Service(Store())", "Service(Store())  # sarj-noqa: SARJ526 -- retained direct owner"),
        _SOURCE.replace("        service =", "        # Keep the authored direct constructor.\n        service ="),
    ):
        assert fix_source(_PATH, source, rule_ids=[_RULE]) == source


_OBSERVER = """import json
from pathlib import Path
import pytest

EVENTS = []
MODE = {mode!r}

class Alternative:
    def read(self):
        return 2

def pytest_generate_tests(metafunc):
    if MODE == "alternative":
        metafunc.parametrize("store_factory", [Alternative])

def pytest_fixture_setup(fixturedef, request):
    if fixturedef.func.__module__ == "test_service":
        if fixturedef.argname != "store_factory":
            raise RuntimeError("unapproved new test-local fixture")
        EVENTS.append("existing-factory-setup")

@pytest.fixture(autouse=True)
def observe_constructor(request, monkeypatch):
    store = request.module.Store
    original = store.__new__
    def allocate(cls):
        EVENTS.append("constructor")
        if MODE == "constructor-error":
            raise RuntimeError("constructor-contract")
        return original(cls)
    monkeypatch.setattr(store, "__new__", staticmethod(allocate))

def pytest_runtest_logreport(report):
    EVENTS.append([report.when, report.outcome])

def pytest_sessionfinish(session, exitstatus):
    Path("events.json").write_text(json.dumps(EVENTS))
"""


@pytest.mark.parametrize("mode", ["canonical", "alternative", "constructor-error"])
def test_autofix_keeps_real_pytest_fixture_graph_and_constructor_contract(tmp_path: Path, mode: str) -> None:
    observed: list[str] = []
    exits: list[int] = []
    for name, source in (("before", _SOURCE), ("after", _FIXED)):
        project = tmp_path / name
        project.mkdir()
        (project / "pyproject.toml").write_text('[project]\nname="guarded-factory-probe"\nversion="0.0.0"\n')
        (project / "test_service.py").write_text(source)
        (project / "conftest.py").write_text(_OBSERVER.format(mode=mode))
        # The bounded subprocess runs the real pinned pytest and its ordinary
        # fixture hooks; source edits and fake setup calls cannot establish this.
        result = subprocess.run(
            [sys.executable, "-m", "pytest", "-q", "test_service.py"],
            cwd=project,
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
        exits.append(result.returncode)
        events = project / "events.json"
        assert events.is_file(), result.stdout + result.stderr
        observed.append(events.read_text())
    assert exits == ([1, 1] if mode == "constructor-error" else [0, 0])
    assert observed[0] == observed[1]
    assert observed[0].count('"constructor"') == (0 if mode == "alternative" else 1)
