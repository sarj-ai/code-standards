from __future__ import annotations

import ast
from pathlib import Path
import sys
from types import ModuleType

import pytest

from sarj_python_lint.__main__ import main
from sarj_python_lint.autofix import fix_source
from sarj_python_lint.rule_base import Severity
from sarj_python_lint.rules.no_unnecessary_docstring import NoUnnecessaryDocstring
from sarj_python_lint.rules.redundant_module_docstring import RedundantModuleDocstring


_PATH = Path("app/service.py")
_RULES = ["no-unnecessary-docstring", "redundant-module-docstring"]


@pytest.mark.parametrize(
    "literal",
    [
        pytest.param('"""Service module."""', id="triple-double"),
        pytest.param("'''Service module.'''", id="triple-single"),
        pytest.param('"Service module."', id="double"),
        pytest.param("'Service module.'", id="single"),
        pytest.param('r"""Service paths include \\network."""', id="raw"),
        pytest.param('u"""Service entry points."""', id="unicode-prefix"),
        pytest.param('"""Service entry points.\\nAdditional details."""', id="escaped-newline"),
        pytest.param('"""Service entry points.\n\nAdditional details.\n"""', id="physical-multiline"),
        pytest.param('(\n    "Service "\n    "entry points."\n)', id="parenthesized-concatenation"),
        pytest.param('"""خدمة الطلبات."""', id="non-ascii"),
        pytest.param('""""""', id="empty"),
    ],
)
@pytest.mark.parametrize("newline", ["\n", "\r\n"], ids=("lf", "crlf"))
def test_module_docstring_deletion_preserves_other_statements_and_converges(literal: str, newline: str) -> None:
    tail = "\nfrom __future__ import annotations\n\nVALUE = 1\n"
    source = (literal + "\n" + tail).replace("\n", newline)
    expected = tail.replace("\n", newline)
    before = ast.parse(source)
    findings = NoUnnecessaryDocstring().check(_PATH, source)
    assert [(finding.line, finding.code, finding.severity) for finding in findings] == [(1, "SARJ420", Severity.ERROR)]
    fixed = fix_source(_PATH, source, rule_ids=_RULES)
    assert fixed == expected
    before.body.pop(0)
    assert ast.dump(ast.parse(fixed)) == ast.dump(before)
    assert ast.get_docstring(ast.parse(fixed)) is None
    assert fix_source(_PATH, fixed, rule_ids=_RULES) == fixed


@pytest.mark.parametrize(
    ("prefix", "tail"),
    [
        pytest.param("#!/usr/bin/env python3\n", "VALUE = 1\n", id="shebang"),
        pytest.param("# coding: utf-8\n", "VALUE = 1\n", id="encoding"),
        pytest.param("# SPDX-License-Identifier: MIT\n", "VALUE = 1\n", id="license"),
        pytest.param("# fmt: off\n", "VALUE = 1\n# fmt: on\n", id="formatter-directive"),
        pytest.param("\n\n", "VALUE = 1", id="leading-blank-and-no-final-newline"),
        pytest.param("", "if __name__ == '__main__':\n    run()\n", id="main-guard"),
        pytest.param("", "", id="docstring-only"),
    ],
)
def test_module_docstring_fix_preserves_headers_directives_and_end_of_file(prefix: str, tail: str) -> None:
    source = f'{prefix}"""Service entry points."""\n{tail}'
    assert fix_source(_PATH, source, rule_ids=_RULES) == prefix + tail


