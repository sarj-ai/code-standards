def test_module_autofix_rejects_unparseable_source_without_rewriting() -> None:
    source = '"""Service module."""\nVALUE = (\n'
    with pytest.raises(ValueError, match="selected Python source could not be parsed"):
        fix_source(_PATH, source, rule_ids=_RULES)


@pytest.mark.parametrize(
    "consumer",
    [
        "help(sys.modules[__name__])",
        "inspect.getdoc(sys.modules[__name__])",
        "current = sys.modules[__name__]\nhelp(current)",
        "current = sys.modules[__name__]\ninspect.getdoc(current)",
    ],
)
def test_direct_current_module_help_and_getdoc_are_consumers(consumer: str) -> None:
    source = '"""Service entry points."""\nimport sys\nimport inspect\n' + consumer + "\n"
    assert NoUnnecessaryDocstring().check(_PATH, source) == []
    assert fix_source(_PATH, source, rule_ids=_RULES) == source


def test_cli_deletes_module_docstring_and_reports_clean_file(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    target = tmp_path / "service.py"
    target.write_text('"""Service entry points."""\nVALUE = 1\n', encoding="utf-8")
    assert main(["check", "--rule", "no-unnecessary-docstring", "--fix", str(target)]) == 0
    assert target.read_text(encoding="utf-8") == "VALUE = 1\n"
    assert "SARJ420" not in capsys.readouterr().out


