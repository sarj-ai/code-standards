@pytest.mark.parametrize(
    ("prefix", "consumer"),
    [
        ("import importlib", "help(importlib.import_module(__name__))"),
        ("from importlib import import_module as load", "help(load(__name__))"),
        ("import importlib", "current = importlib.import_module(__name__)\nhelp(current)"),
    ],
)
def test_importlib_current_module_consumers_are_preserved(prefix: str, consumer: str) -> None:
    source = f'"""Entry points."""\n{prefix}\n{consumer}\n'
    assert NoUnnecessaryDocstring().check(_PATH, source) == []
    assert RedundantModuleDocstring().check(_PATH, source) == []
    assert fix_source(_PATH, source, rule_ids=_RULES) == source


@pytest.mark.parametrize(
    ("imports", "consumer"),
    [
        ("import __main__\nimport inspect", "inspect.getdoc(__main__)"),
        ("import __main__ as entry\nfrom inspect import getdoc", "getdoc(entry)"),
        ("from __main__ import __doc__ as description", "description"),
    ],
)
def test_main_module_metadata_fix_preserves_runtime_description(
    imports: str, consumer: str, monkeypatch: pytest.MonkeyPatch
) -> None:
    source = '"""Command help."""\n' + imports + "\nDESCRIPTION = " + consumer + "\n"
    fixed = fix_source(Path("cli.py"), source, rule_ids=_RULES)
    assert fixed == source
    module = ModuleType("__main__")
    monkeypatch.setitem(sys.modules, "__main__", module)
    exec(  # ruff: ignore[exec-builtin] -- execute only the authored module-description fixture.
        compile(fixed, "cli.py", "exec", dont_inherit=True), module.__dict__
    )
    assert module.__dict__["DESCRIPTION"] == "Command help."


@pytest.mark.parametrize(
    "imports",
    [
        "import __main__",
        "import __main__ as entry",
        "from __main__ import application",
        "import pydoc",
        "import pydoc as documentation",
        "from pydoc import render_doc as describe",
    ],
)
def test_unresolved_module_documentation_capabilities_withhold_fixes_without_inventing_consumers(imports: str) -> None:
    source = '"""Application module."""\n' + imports + "\nVALUE = 1\n"
    assert RedundantModuleDocstring().check(Path("app/library.py"), source)
    assert NoUnnecessaryDocstring().check(Path("app/library.py"), source)
    assert fix_source(Path("app/library.py"), source, rule_ids=_RULES) == source


def test_pydoc_generated_help_remains_unchanged(monkeypatch: pytest.MonkeyPatch) -> None:
    source = '"""Command help."""\nimport pydoc\nDESCRIPTION = pydoc.render_doc(__name__, renderer=pydoc.plaintext)\n'
    fixed = fix_source(Path("cli.py"), source, rule_ids=_RULES)
    assert fixed == source
    module = ModuleType("__main__")
    monkeypatch.setitem(sys.modules, "__main__", module)
    exec(  # ruff: ignore[exec-builtin] -- execute only the authored standard-library help fixture.
        compile(fixed, "cli.py", "exec", dont_inherit=True), module.__dict__
    )
    assert "Command help." in module.__dict__["DESCRIPTION"]


