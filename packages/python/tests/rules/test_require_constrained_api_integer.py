from pathlib import Path
from typing import TYPE_CHECKING

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.require_constrained_api_integer import RequireConstrainedApiInteger


_HEADER = "from fastapi import APIRouter, Query, Path, Depends, Body, Header, Cookie, Form, File\nfrom typing import Annotated, Optional\nfrom pydantic import PositiveInt, Field\nfrom annotated_types import Gt\nrouter = APIRouter()\n@router.get('/versions')\n"


if TYPE_CHECKING:
    from sarj_python_lint.rule_base import Rule


@pytest.fixture
def rule() -> Rule:
    return RequireConstrainedApiInteger()


def test_documented_examples() -> None:
    verify_native_rule(RequireConstrainedApiInteger, analyze)


@pytest.mark.parametrize(
    "parameter",
    [
        "limit: int = 25",
        "version: int",
        "limit: int | None = None",
        "limit: Optional[int] = None",
        "limit: Annotated[int, Query()] = 25",
        "*, limit: int = 25",
    ],
)
def test_unbounded_integer_request_parameter(rule: Rule, parameter: str) -> None:
    source = _HEADER + f"def versions({parameter}):\n    return 1\n"
    assert len(rule.check(Path("api.py"), source)) == 1


@pytest.mark.parametrize(
    "parameter",
    [
        "limit: PositiveInt = 25",
        "limit: int = Query(25, gt=0)",
        "version: Annotated[int, Path(ge=1)]",
        "limit: Annotated[int, Field(le=100)] = 25",
        "limit: Annotated[int, Gt(0)] = 25",
        "limit: int = Depends(get_limit)",
        "limit: Annotated[int, Body()]",
        "limit: int = Header()",
        "limit: int = Cookie()",
        "limit: int = Form()",
        "limit: int = File()",
        "limit: int | str = 'all'",
        "limit: list[int] = []",
    ],
)
def test_explicit_numeric_domains_and_nonquery_inputs(rule: Rule, parameter: str) -> None:
    source = _HEADER + f"async def versions({parameter}):\n    return 1\n"
    assert rule.check(Path("api.py"), source) == []


def test_nonroute_test_generated_and_suppression(rule: Rule) -> None:
    source = _HEADER + "def versions(limit: int = 25):\n    return limit\n"
    assert rule.check(Path("api.py"), source.replace("@router.get('/versions')\n", "")) == []
    assert rule.check(Path("tests/test_api.py"), source) == []
    assert rule.check(Path("api.py"), "# Generated by protoc. Do not edit.\n" + source) == []
    assert (
        rule.check(
            Path("api.py"), source.replace("= 25):", "= 25):  # sarj-noqa: SARJ553 -- signed legacy wire contract")
        )
        == []
    )
    assert rule.check(Path("api.py"), "def versions(:") == []
