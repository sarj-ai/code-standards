from __future__ import annotations

from pathlib import Path

import pytest
from sarj_rule_contracts import Severity
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.prefer_outcome_variants import PreferOutcomeVariants


def test_documented_examples() -> None:
    verify_native_rule(PreferOutcomeVariants, analyze)


@pytest.mark.parametrize(
    ("prefix", "header"),
    [
        ("from pydantic import BaseModel\n", "class CheckResult(BaseModel):"),
        ("import pydantic as p\n", "class CheckResult(p.BaseModel):"),
        ("from typing import TypedDict\n", "class CheckResult(TypedDict):"),
        ("from dataclasses import dataclass\n", "@dataclass\nclass CheckResult:"),
        ("import dataclasses as d\n", "@d.dataclass(frozen=True)\nclass CheckResult:"),
        ("from msgspec import Struct\n", "class CheckResult(Struct):"),
        ("from attrs import define\n", "@define\nclass CheckResult:"),
    ],
)
@pytest.mark.parametrize(
    "fields",
    [
        "    passed: bool = False\n    error: str | None = None\n    audio: bytes | None = None\n",
        "    ok: bool\n    exception: Exception | None = None\n",
        "    status: Literal['success', 'error']\n    failure: str | None = None\n",
        "    error: Optional[str] = None\n    value: int | None = None\n",
        "    error: Union[str, None] = None\n    output: bytes | None = None\n",
        "    error: 'str | None' = None\n    reference: str\n",
        "    error: Annotated[str | None, 'context'] = None\n    reference: str\n",
    ],
)
def test_nullable_outcomes_across_record_forms(prefix: str, header: str, fields: str) -> None:
    source = "from typing import Annotated, Literal, Optional, Union\n" + prefix + header + "\n" + fields
    findings = PreferOutcomeVariants().check(Path("app/models.py"), source)
    assert len(findings) == 1
    assert findings[0].severity is Severity.WARNING
    assert "Success | Error" in findings[0].message


@pytest.mark.parametrize(
    "source",
    [
        "from pydantic import BaseModel\nclass Measurement(BaseModel):\n    error: float | None\n    value: float\n",
        "from pydantic import BaseModel\nclass Health(BaseModel):\n    connected: bool\n    last_error: str | None\n",
        "from pydantic import BaseModel\nclass Outcome(BaseModel):\n    error: str\n    context: str\n",
        "from pydantic import BaseModel\nclass Success(BaseModel):\n    passed: Literal[True] = True\n    value: int\n",
        "from pydantic import BaseModel\nclass Error(BaseModel):\n    passed: Literal[False] = False\n    error: str\n",
        "class BaseModel: pass\nclass CheckResult(BaseModel):\n    error: str | None\n    value: int | None\n",
        "from typing import ClassVar\nfrom pydantic import BaseModel\nclass CheckResult(BaseModel):\n    error: ClassVar[str | None] = None\n    value: int | None\n",
        "from pydantic import BaseModel\nclass CheckResult(BaseModel):\n    error: str | None = None  # sarj-noqa: SARJ571 -- This external snapshot intentionally preserves its historic wire shape.\n    value: int | None = None\n",
        "# Generated by protoc. Do not edit.\nfrom pydantic import BaseModel\nclass CheckResult(BaseModel):\n    error: str | None\n    value: int | None\n",
    ],
)
def test_independent_error_context_and_existing_variants(source: str) -> None:
    assert PreferOutcomeVariants().check(Path("app/models.py"), source) == []


def test_nullable_outcome_detection_is_not_name_only() -> None:
    source = "from pydantic import BaseModel\nclass Result(BaseModel):\n    value: str\n"
    assert PreferOutcomeVariants().check(Path("app/models.py"), source) == []


def test_nullable_payload_heuristic_does_not_require_result_name() -> None:
    source = (
        "from pydantic import BaseModel\nclass Delivery(BaseModel):\n    error: str | None\n    data: bytes | None\n"
    )
    assert len(PreferOutcomeVariants().check(Path("app/models.py"), source)) == 1


@pytest.mark.parametrize("error_type", ["float", "int", "NonNegativeFloat", "Decimal"])
def test_numeric_uncertainty_is_not_a_failure_variant(error_type: str) -> None:
    source = (
        "from decimal import Decimal\nfrom pydantic import BaseModel, NonNegativeFloat\n"
        "class ForecastResult(BaseModel):\n"
        f"    error: {error_type} | None = None\n"
        "    value: float\n"
    )
    assert PreferOutcomeVariants().check(Path("app/models.py"), source) == []
