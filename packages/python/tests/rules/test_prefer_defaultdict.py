def test_multiple_updates_are_one_accumulator_warning(rule: Rule) -> None:
    source = "def group(rows):\n    groups = {}\n    for key, value in rows:\n        groups.setdefault(key, []).append(value)\n        groups.setdefault(key, []).append(value + 1)\n    return dict(groups)\n"
    assert len(rule.check(Path("tests/test_group.py"), source)) == 1


def test_nested_control_flow_and_async_loop_keep_the_owner(rule: Rule) -> None:
    source = "async def group(rows):\n    groups = {}\n    async for key, value in rows:\n        if value:\n            groups.setdefault(key, []).append(value)\n    return dict(groups)\n"
    assert len(rule.check(Path("app/group.py"), source)) == 1


@pytest.mark.parametrize("header", ["for row in rows", "async for row in rows", "while rows"])
def test_loop_else_runs_once_on_normal_completion(rule: Rule, header: str) -> None:
    source = f"async def group(rows):\n    groups = {{}}\n    {header}:\n        pass\n    else:\n        groups.setdefault('one', []).append(1)\n    return dict(groups)\n"
    assert rule.check(Path("app/group.py"), source) == []
