from pathlib import Path
from typing import TYPE_CHECKING

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.prefer_defaultdict import PreferDefaultdict


if TYPE_CHECKING:
    from sarj_python_lint.rule_base import Rule


@pytest.fixture
def rule() -> Rule:
    return PreferDefaultdict()


def test_documented_examples() -> None:
    verify_native_rule(PreferDefaultdict, analyze)


@pytest.mark.parametrize("header", ["groups = {}", "groups: dict[str, list[int]] = {}"])
def test_owned_grouping_dictionary(rule: Rule, header: str) -> None:
    source = f"def group(rows):\n    {header}\n    for key, value in rows:\n        groups.setdefault(key, []).append(value)\n    return sorted(groups.items())\n"
    findings = rule.check(Path("app/group.py"), source)
    assert len(findings) == 1
    assert findings[0].line == 4


