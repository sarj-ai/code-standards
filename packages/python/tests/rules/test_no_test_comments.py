from pathlib import Path
from typing import TYPE_CHECKING

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.no_test_comments import NoTestComments


if TYPE_CHECKING:
    from sarj_python_lint.rule_base import Rule


@pytest.fixture
def rule() -> Rule:
    return NoTestComments()


def test_documented_examples() -> None:
    verify_native_rule(NoTestComments, analyze)


@pytest.mark.parametrize("comment", ["# Setup the store", "assert ready  # The store exists"])
def test_real_test_comments(rule: Rule, comment: str) -> None:
    source = f"def test_ready():\n    {comment}\n    assert ready\n"
    assert len(rule.check(Path("tests/test_ready.py"), source)) == 1


@pytest.mark.parametrize(
    "source",
    [
        "# ruff: noqa: F401\nimport os\n",
        "# pyright: strict\nvalue = 1\n",
        "# Copyright 2026 Example\nvalue = 1\n",
        "# Copyright 2026 Example\n# Permission is hereby granted, free of charge.\n# This software is provided without warranty.\nvalue = 1\n",
        "#!/usr/bin/env python\nvalue = 1\n",
        "# -*- coding: utf-8 -*-\nvalue = 1\n",
        "value = '# comment-looking data'\n",
        'def test_ready():\n    """A documentation contract."""\n    assert ready\n',
        "# Generated by protoc. Do not edit.\n# retained generated comment\nvalue = 1\n",
        "# retained reason  # sarj-noqa: SARJ551 -- documents an external protocol contract\nvalue = 1\n",
    ],
)
def test_directives_legal_notices_and_strings(rule: Rule, source: str) -> None:
    assert rule.check(Path("tests/test_ready.py"), source) == []


def test_production_comments_and_malformed_source(rule: Rule) -> None:
    assert rule.check(Path("app/service.py"), "# explain a boundary\nvalue = 1\n") == []
    assert rule.check(Path("tests/test_ready.py"), "def test_ready(:\n# malformed") == []


def test_selected_rule_reports_phase_comments_and_test_prose(rule: Rule) -> None:
    source = "def test_ready():\n    # Arrange\n    value = 1\n    # A stale value is rejected.\n    assert value\n"
    broad = rule.check(Path("tests/test_ready.py"), source)
    assert [finding.line for finding in broad] == [2, 4]


@pytest.mark.parametrize(
    ("path", "source", "expected"),
    [
        ("rules/uncontrolled_randomness_in_test.py", "# Explain the production detector.\nclass Detector: pass\n", 0),
        ("widget_test.py", "# Arrange\ndef test_widget():\n    assert widget()\n", 1),
        ("testing/helpers.py", "# Prepare the helper.\ndef helper(): pass\n", 1),
        ("tests/helpers.py", "# Prepare the helper.\ndef helper(): pass\n", 1),
    ],
)
def test_directory_ownership_and_test_declarations(rule: Rule, path: str, source: str, expected: int) -> None:
    assert len(rule.check(Path(path), source)) == expected
