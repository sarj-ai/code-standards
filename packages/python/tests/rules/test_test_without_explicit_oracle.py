from pathlib import Path
import textwrap

import pytest

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rule_base import Severity
from sarj_python_lint.rules.test_without_explicit_oracle import NoExplicitTestOracle


@pytest.mark.parametrize(
    "source",
    [
        "def test_delivery():\n    deliver('hello')\n",
        "async def test_delivery():\n    await deliver('hello')\n",
        "class TestDelivery:\n    def test_delivery(self):\n        deliver('hello')\n",
        "def test_delivery():\n    def unused():\n        assert delivered\n    deliver('hello')\n",
        "def test_delivery():\n    callback = lambda: assert_delivery()\n    deliver('hello')\n",
        "def test_exporter_does_not_fail_job():\n    await_exporter()\n",
    ],
)
def test_reports_a_review_candidate_without_claiming_the_test_is_invalid(source: str) -> None:
    [finding] = NoExplicitTestOracle().check(Path("tests/test_delivery.py"), source)
    assert finding.code == "SARJ495"
    assert finding.severity is Severity.WARNING


@pytest.mark.parametrize(
    "source",
    [
        "def test_delivery():\n    assert delivered == ['hello']\n",
        "def test_delivery():\n    assert result is None\n",
        "def test_delivery():\n    sender.send.assert_called_once_with('hello')\n",
        "import pytest\ndef test_delivery():\n    with pytest.raises(ValueError):\n        deliver()\n",
        "from pytest import raises as fails\ndef test_delivery():\n    with fails(ValueError):\n        deliver()\n",
        "def inspect_result(value):\n    assert value == ['hello']\ndef test_delivery():\n    inspect_result(deliver())\n",
        "def inner(value):\n    assert value\ndef outer(value):\n    inner(value)\ndef test_delivery():\n    outer(deliver())\n",
        "class TestDelivery:\n    def inspect_result(self, value):\n        assert value\n    def test_delivery(self):\n        self.inspect_result(deliver())\n",
        "def test_delivery(check):\n    check(deliver())\n",
        "def test_delivery():\n    raise AssertionError('not delivered')\n",
        "def helper():\n    deliver()\n",
        "class Container:\n    def test_delivery(self):\n        deliver()\n",
        "class TestDelivery:\n    def __init__(self):\n        pass\n    def test_delivery(self):\n        deliver()\n",
        "__test__ = False\ndef test_delivery():\n    deliver()\n",
        "__test__: bool = False\ndef test_delivery():\n    deliver()\n",
        "class TestDelivery:\n    __test__ = False\n    def test_delivery(self):\n        deliver()\n",
        "def test_delivery():\n    deliver()\ntest_delivery.__test__ = False\n",
        "def test_delivery():\n    deliver()\ntest_delivery.__test__: bool = False\n",
        "class TestDelivery:\n    def test_delivery(self):\n        deliver()\nTestDelivery.test_delivery.__test__ = False\n",
        "import pytest\npytestmark = pytest.mark.skip(reason='optional')\ndef test_delivery():\n    deliver()\n",
        "import pytest\nclass TestDelivery:\n    pytestmark = [pytest.mark.lto]\n    def test_delivery(self):\n        deliver()\n",
        "import pytest\n@pytest.mark.skip(reason='optional')\ndef test_delivery():\n    deliver()\n",
        "import pytest\n@pytest.mark.lto\ndef test_delivery():\n    deliver()\n",
        "@given(values)\ndef test_delivery():\n    deliver()\n",
        "def test_delivery(benchmark):\n    benchmark(deliver)\n",
        "# Generated by a fixture generator.\ndef test_delivery():\n    deliver()\n",
        "def test_broken(\n",
    ],
)
def test_preserves_oracles_and_abstains_on_uncollected_or_uncertain_cases(source: str) -> None:
    assert NoExplicitTestOracle().check(Path("tests/test_delivery.py"), textwrap.dedent(source)) == []


def test_explicit_selection_honors_local_suppression(tmp_path: Path) -> None:
    target = tmp_path / "test_delivery.py"
    target.write_text(
        "def test_delivery():  # sarj-noqa: SARJ495 -- successful execution is the contract\n    deliver()\n"
    )
    assert analyze([NoExplicitTestOracle.id], [target]) == []
