from __future__ import annotations

from pathlib import Path

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rule_base import Severity
from sarj_python_lint.rules.prefer_decimal_money import PreferDecimalMoney


_HEADER = "from pydantic import BaseModel, Field\nfrom typing import Annotated, ClassVar, Optional\n"


def test_documented_examples() -> None:
    verify_native_rule(PreferDecimalMoney, analyze)


@pytest.mark.parametrize(
    "source",
    [
        _HEADER + "class Deal(BaseModel):\n    purchase_price: float\n",
        "def transfer(amount: float) -> None: pass\n",
        "class Limits:\n    def max_amount(self) -> float | None: return None\n",
        "from dataclasses import dataclass as record\n@record\nclass Quote:\n    annual_fee_sar: float\n",
        _HEADER + "class Deal(BaseModel):\n    amount: Annotated[float, Field(gt=0)]\n",
        "import typing_extensions as te\nclass Quote(te.TypedDict, total=False):\n    price: te.NotRequired[float]\n",
        "from typing import TypedDict\nclass Parent(TypedDict): pass\nclass Quote(Parent):\n    price: float\n",
        (
            "from typing import TypedDict\nimport pydantic as pd\n@pd.with_config(pd.ConfigDict(strict=True))\n"
            "class Quote(TypedDict):\n    price: float\n"
        ),
        (
            "from typing import TypedDict\nimport pydantic as pd\nclass Parent(TypedDict): pass\n"
            "@pd.with_config(pd.ConfigDict(strict=True))\nclass Quote(Parent, total=False):\n    price: float\n"
        ),
        _HEADER + "async def transfer(*, balance: 'Optional[float]') -> None: pass\n",
        "import builtins as b\ndef amount() -> b.float: return 0.0\n",
    ],
)
def test_monetary_float_annotations_warn(source: str) -> None:
    findings = PreferDecimalMoney().check(Path("app/deals.py"), source)
    assert len(findings) == 1
    assert findings[0].code == PreferDecimalMoney.code
    assert findings[0].severity is Severity.WARNING
    assert "Decimal" in findings[0].message


@pytest.mark.parametrize(
    "field",
    [
        "amount: Decimal",
        "amount: SarAmount",
        "total: float",
        "error_rate: float",
        "fee_count: int",
        "time_cost: int",
        "amount: int",
        "interest_rate_usd: float",
        "price_type: float",
        "usd: float",
        "price: list[float]",
        "price: float | str",
        "price: ClassVar[float]",
    ],
)
def test_money_near_misses(field: str) -> None:
    source = _HEADER + "from decimal import Decimal\nclass Quote(BaseModel):\n    " + field + "\n"
    assert PreferDecimalMoney().check(Path("app/deals.py"), source) == []


@pytest.mark.parametrize(
    "source",
    [
        "class Quote:\n    price: float\n",
        "class TypedDict: pass\nclass Quote(TypedDict):\n    price: float\n",
        "from typing import NamedTuple\nclass Quote(NamedTuple):\n    price: float\n",
        "from pydantic import BaseModel\nBaseModel = object\nclass Quote(BaseModel):\n    price: float\n",
        "import typing as t\nt.TypedDict = object\nclass Quote(t.TypedDict):\n    price: float\n",
        (
            "from typing import TypedDict\nimport pydantic as pd\npd.with_config = replacement\n"
            "@pd.with_config({})\nclass Quote(TypedDict):\n    price: float\n"
        ),
        "class float: pass\ndef transfer(amount: float) -> None: pass\n",
        "def transfer[float](amount: float) -> None: pass\n",
        "from typing import NewType\nSarAmount = NewType('SarAmount', float)\ndef transfer(amount: SarAmount): pass\n",
        "# Generated by protoc. Do not edit.\ndef transfer(amount: float) -> None: pass\n",
        f"def transfer(amount: float) -> None: pass  # sarj-noqa: {PreferDecimalMoney.code} -- external contract\n",
        "def transfer(amount: float\n",
    ],
)
def test_monetary_float_requires_proven_boundaries(source: str) -> None:
    assert PreferDecimalMoney().check(Path("app/deals.py"), source) == []


@pytest.mark.parametrize(
    ("comment", "expected"),
    [
        ("", PreferDecimalMoney.code),
        (f"  # sarj-noqa: {PreferDecimalMoney.code} -- external contract", "SARJ530"),
    ],
)
def test_money_warning_takes_precedence_at_the_field(tmp_path: Path, comment: str, expected: str) -> None:
    path = tmp_path / "deals.py"
    path.write_text(_HEADER + f"class Quote(BaseModel):\n    amount: float = Field(gt=0){comment}\n")
    findings = analyze([PreferDecimalMoney.id, "prefer-typed-settings-field"], [path], root=tmp_path)
    assert [(finding.code, finding.line) for finding in findings] == [(expected, 4)]
