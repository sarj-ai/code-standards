from pathlib import Path
from typing import TYPE_CHECKING

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.no_value_error_forwarder import NoValueErrorForwarder


if TYPE_CHECKING:
    from sarj_python_lint.rule_base import Rule


@pytest.fixture
def rule() -> Rule:
    return NoValueErrorForwarder()


def test_documented_examples() -> None:
    verify_native_rule(NoValueErrorForwarder, analyze)


@pytest.mark.parametrize("message", ["message", "'invalid input'"])
def test_live_plain_forwarder(rule: Rule, message: str) -> None:
    findings = rule.check(
        Path("app/parse.py"), f"def fail(message):\n    raise ValueError({message})\nfail('bad')\nfail('worse')\n"
    )
    assert len(findings) == 1
    assert findings[0].line == 1


@pytest.mark.parametrize(
    "source",
    [
        "def fail(message):\n    raise ValueError(message)\n",
        "def fail(message):\n    raise ValueError(message)\nregister(fail)\nfail('bad')\n",
        "class Handler:\n    def fail(self, message):\n        raise ValueError(message)\n",
        "@validator\ndef fail(message):\n    raise ValueError(message)\nfail('bad')\n",
        "async def fail(message):\n    raise ValueError(message)\nfail('bad')\n",
        "def fail(message):\n    raise ValueError(f'invalid: {message}')\nfail('bad')\n",
        "def fail(message):\n    raise ValueError(render(message))\nfail('bad')\n",
        "def fail(message):\n    raise ValueError(message) from None\nfail('bad')\n",
        "def fail(message=build_message()):\n    raise ValueError(message)\nfail()\n",
        "def fail(*messages):\n    raise ValueError('bad')\nfail()\n",
        "def fail(message):\n    log(message)\n    raise ValueError(message)\nfail('bad')\n",
        "def fail(message, ValueError):\n    raise ValueError(message)\nfail('bad', Factory)\n",
        "ValueError = CustomError\ndef fail(message):\n    raise ValueError(message)\nfail('bad')\n",
        "def fail(message):\n    raise TypeError(message)\nfail('bad')\n",
        "def fail(message):\n    raise ValueError(message)\nfail = custom\nfail('bad')\n",
        "# Generated by tool. Do not edit.\ndef fail(message):\n    raise ValueError(message)\nfail('bad')\n",
        "def fail(:",
        "def fail(message):  # sarj-noqa: SARJ580 -- Preserve the external failure callback.\n    raise ValueError(message)\nfail('bad')\n",
    ],
)
def test_contract_and_semantic_boundaries(rule: Rule, source: str) -> None:
    assert rule.check(Path("app/parse.py"), source) == []


def test_docstring_does_not_hide_forwarding(rule: Rule) -> None:
    source = 'def fail(message):\n    """Reject a message."""\n    raise ValueError(message)\nfail("bad")\n'
    assert len(rule.check(Path("tests/test_parse.py"), source)) == 1
