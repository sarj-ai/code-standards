from __future__ import annotations

from pathlib import Path

import pytest
from sarj_rule_contracts import Severity
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.prefer_secret_field_type import PreferSecretFieldType


_MODEL = "from pydantic import BaseModel\nclass Credential(BaseModel):\n"
_SETTINGS = "from pydantic_settings import BaseSettings\nclass CloudflareSettings(BaseSettings):\n"
_PATH = Path("app/models.py")


def test_documented_examples() -> None:
    verify_native_rule(PreferSecretFieldType, analyze)


@pytest.mark.parametrize(
    ("source", "preferred", "line"),
    [
        (_SETTINGS + "    api_token: str\n", "SecretStr", 3),
        (_MODEL + "    access_token: str | None = None\n", "SecretStr", 3),
        (_MODEL + '    client_secret: "bytes | None"\n', "SecretBytes", 3),
        (
            "from typing import Annotated, Optional\n"
            + _MODEL
            + "    signing_secret: Annotated[Optional[bytes], 'metadata']\n",
            "SecretBytes",
            4,
        ),
    ],
)
def test_plaintext_credentials(source: str, preferred: str, line: int) -> None:
    findings = PreferSecretFieldType().check(_PATH, source)
    assert len(findings) == 1
    assert preferred in findings[0].message
    assert findings[0].line == line
    assert findings[0].severity is Severity.WARNING


def test_imported_pydantic_base_reports_only_declared_fields(tmp_path: Path) -> None:
    package = tmp_path / "app"
    package.mkdir()
    (package / "__init__.py").touch()
    base = package / "base.py"
    base.write_text("import pydantic as pd\nclass Parent(pd.BaseModel):\n    client_secret: str\n")
    child = package / "child.py"
    child.write_text("from app.base import Parent\nclass Child(Parent):\n    access_token: str\n")

    findings = analyze(["prefer-secret-field-type"], [base, child], root=tmp_path)

    assert len(findings) == 2
    assert {finding.path.name for finding in findings} == {base.name, child.name}
    assert all(finding.line == 3 for finding in findings)


def test_near_miss_fields() -> None:
    source = (
        "from pathlib import Path\nfrom typing import ClassVar\nfrom pydantic import SecretBytes, SecretStr\n"
        + _MODEL
        + "    api_token: SecretStr\n"
        + "    client_secret: SecretBytes | None\n"
        + "    next_page_token: str\n"
        + "    token_count: int\n"
        + "    password_path: Path\n"
        + "    passwords: list[str]\n"
        + "    signing_secret: str | SecretBytes\n"
        + "    auth_token: ClassVar[str]\n"
        + "    _access_token: str\n"
    )
    assert PreferSecretFieldType().check(_PATH, source) == []


@pytest.mark.parametrize(
    "source",
    [
        "from dataclasses import dataclass\n@dataclass\nclass Model:\n    access_token: str\n",
        "from pydantic.dataclasses import dataclass\n@dataclass\nclass Model:\n    access_token: str\n",
        "class BaseModel: pass\nclass Model(BaseModel):\n    access_token: str\n",
        "from pydantic import BaseModel\nBaseModel = object\nclass Model(BaseModel):\n    access_token: str\n",
        "from pydantic import BaseModel\nclass Model(BaseModel):\n    str = bytes\n    access_token: str\n",
        "def issue(access_token: str) -> None: pass\n",
        "# Generated by protoc. Do not edit.\n" + _MODEL + "    access_token: str\n",
        "not python (",
    ],
)
def test_requires_pydantic_model_fields(source: str) -> None:
    assert PreferSecretFieldType().check(_PATH, source) == []


def test_suppression_does_not_hide_the_settings_input_error(tmp_path: Path) -> None:
    path = tmp_path / "settings.py"
    path.write_text(_SETTINGS + "    api_token: str  # sarj-noqa: SARJ613 -- wire format requires raw text\n")
    findings = analyze(["prefer-secret-field-type", "require-hidden-settings-input"], [path], root=tmp_path)
    assert [(finding.code, finding.line, finding.severity) for finding in findings] == [("SARJ575", 2, Severity.ERROR)]
