from __future__ import annotations

from typing import TYPE_CHECKING

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.autofix import fix_source
from sarj_python_lint.rule_base import Severity
from sarj_python_lint.rules.prefer_frozen_dataclass import PreferFrozenDataclass


if TYPE_CHECKING:
    from pathlib import Path


_RULE = PreferFrozenDataclass.id
_IMPORT = "from dataclasses import dataclass\n"
_PRIVATE = _IMPORT + "\n@dataclass\nclass _Record:\n    amount: int\n"
_PUBLIC = _PRIVATE.replace("_Record", "Record").replace("@dataclass", "@dataclass(frozen=False, kw_only=True)")


@pytest.fixture
def module(tmp_path: Path) -> Path:
    (tmp_path / "pyproject.toml").write_text("[project]\nname = 'fixture'\nversion = '0.1.0'\n", encoding="utf-8")
    return tmp_path / "records.py"


def test_documented_examples() -> None:
    verify_native_rule(PreferFrozenDataclass, analyze)


def test_reports_playback_binding(module: Path) -> None:
    module.write_text(
        _IMPORT
        + """
import asyncio

@dataclass(frozen=False, slots=True)
class _Playback:
    pcm: bytes
    completed: asyncio.Future[None]

def finish(playback: _Playback) -> None:
    playback.completed.set_result(None)

queued: asyncio.Queue[_Playback] = asyncio.Queue()
""",
        encoding="utf-8",
    )
    (finding,) = analyze([_RULE], [module])
    assert (finding.line, finding.severity, finding.fixes) == (6, Severity.ERROR, ())


@pytest.mark.parametrize(
    "source",
    [
        _IMPORT + "@dataclass\nclass NormalExit:\n    pass\n",
        _IMPORT + "from dataclasses import KW_ONLY as Marker\n@dataclass\nclass _Marker:\n    _: Marker\n",
        _PRIVATE.replace("amount: int", "amount: ClassVar[int]").replace(
            _IMPORT, _IMPORT + "from typing import ClassVar\n"
        ),
        _IMPORT
        + """
from collections import deque
import threading

@dataclass
class RateLimit:
    sent: dict[str, deque[float]]
    lock: threading.Lock
""",
        _PRIVATE.replace("amount: int", "amount: list[int]"),
        "from asyncio import Queue\n" + _PRIVATE.replace("amount: int", "amount: Queue[int]"),
        _PRIVATE.replace(
            "from dataclasses import dataclass", "from dataclasses import dataclass, InitVar as Input"
        ).replace("amount: int", "amount: Input[int]"),
        _PRIVATE + "    def __post_init__(self):\n        pass\n",
        _PRIVATE + "    def configure(record):\n        record.extra = 1\n",
        _PRIVATE + "class Derived(_Record):\n    pass\n",
        _PRIVATE + "Parent = _Record\nclass Derived(Parent):\n    pass\n",
        _PRIVATE + "def update(record):\n    record.amount += 1\n",
        _PRIVATE + "def clear(record):\n    del record.amount\n",
        _PRIVATE + "def inspect(record):\n    return record.__dict__\n",
        _PRIVATE + "def update(record):\n    object.__setattr__(record, 'extra', 1)\n",
        _PRIVATE + "from builtins import setattr as set_attribute\n",
        _PRIVATE.replace("@dataclass", "@dataclass\n@other"),
        _PRIVATE.replace("@dataclass", "@dataclass(**options)"),
        _PRIVATE.replace("@dataclass", "dataclass = other\n@dataclass"),
        _PRIVATE.replace("class _Record:", "class _Record:  # sarj-noqa: SARJ607 -- intentionally mutable"),
        "# Code generated by a fixture. Do not edit.\n" + _PRIVATE,
    ],
)
def test_skips_unproven_records(module: Path, source: str) -> None:
    module.write_text(source, encoding="utf-8")
    assert analyze([_RULE], [module]) == []


@pytest.mark.parametrize(
    "consumer",
    [
        "def update(record):\n    record.amount = 3\n",
        "def update(record):\n    setattr(record, 'amount', 3)\n",
        "from records import Record as Parent\ndef derive():\n    class Child(Parent):\n        pass\n    return Child\n",
        "def broken(record):\n    record.amount =\n",
    ],
)
def test_checks_the_project_for_public_records(module: Path, consumer: str) -> None:
    module.write_text(_PUBLIC, encoding="utf-8")
    module.with_name("consumer.py").write_text(consumer, encoding="utf-8")
    assert analyze([_RULE], [module]) == []


@pytest.mark.parametrize(("record", "attribute"), [(_PRIVATE, "amount"), (_PUBLIC, "extra")])
def test_reports_records_without_in_scope_field_writes(module: Path, record: str, attribute: str) -> None:
    module.write_text(record, encoding="utf-8")
    module.with_name("unrelated.py").write_text(f"def update(other):\n    other.{attribute} = 3\n", encoding="utf-8")
    assert len(analyze([_RULE], [module])) == 1


def test_skips_tests(module: Path) -> None:
    path = module.with_name("test_records.py")
    path.write_text(_PRIVATE, encoding="utf-8")
    assert analyze([_RULE], [path]) == []


@pytest.mark.parametrize(
    ("options", "fixed_options"),
    [("eq=False", "frozen=True, eq=False"), ("eq=False, frozen=False", "eq=False, frozen=True")],
)
def test_fixes_private_records_with_a_stable_hash(module: Path, options: str, fixed_options: str) -> None:
    source = _PRIVATE.replace("@dataclass", f"@dataclass({options})")
    fixed = fix_source(module, source, rule_ids=[_RULE])
    assert fixed == source.replace(options, fixed_options)
    module.write_text(fixed, encoding="utf-8")
    assert analyze([_RULE], [module]) == []


def test_autofix_skips_modules_with_undeclared_attribute_writes(module: Path) -> None:
    source = _PRIVATE.replace("@dataclass", "@dataclass(eq=False)") + "def annotate(record):\n    record.extra = 1\n"
    assert fix_source(module, source, rule_ids=[_RULE]) == source
