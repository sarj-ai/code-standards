def test_temporal_advice_supersedes_generic_numeric_advice(tmp_path: Path) -> None:
    path = tmp_path / "models.py"
    path.write_text(_HEADER + "    created_ms: int\n    count: int = 0\n")
    findings = analyze(["prefer-semantic-temporal-types", "prefer-typed-settings-field"], [path], root=tmp_path)
    assert [(finding.code, finding.line) for finding in findings] == [("SARJ573", 3), ("SARJ530", 4)]


