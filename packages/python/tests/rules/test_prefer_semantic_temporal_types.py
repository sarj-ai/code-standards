def test_pydantic_string_instants_have_distinct_advice() -> None:
    source = """\
from typing import ClassVar

from pydantic import AwareDatetime, BaseModel
from pydantic_settings import BaseSettings

class Parent(BaseModel): ...

class Delivery(Parent):
    queued_at: str
    expires_at: AwareDatetime
    received_timestamp: str | None
    started_at: float
    queued_ts: str
    sent_at: ClassVar[str] = 'now'
    updated_at: str  # sarj-noqa: SARJ573 -- format defined by the wire contract

class Settings(BaseSettings):
    activated_at: 'str | None'
"""
    findings = PreferSemanticTemporalTypes().check(Path("app/models.py"), source)
    assert [finding.line for finding in findings] == [9, 11, 18]
    assert all("ISO datetime field" in finding.message for finding in findings)


