def test_function_temporal_annotations_cover_parameter_kinds_and_returns() -> None:
    source = """\
from typing import Annotated

def flush(
    timeout_seconds: float | None,
    /,
    interval_minutes: Annotated[int, 'metadata'] = 0,
    *delay_seconds: float,
    elapsed_ms: int,
    **duration_ms: int,
) -> None: ...

async def elapsed_s() -> float: ...
"""
    findings = PreferSemanticTemporalTypes().check(Path("app/client.py"), source)
    assert [finding.line for finding in findings] == [4, 6, 7, 8, 9, 12]
    assert all("timedelta" in finding.message and finding.severity is Severity.WARNING for finding in findings)


