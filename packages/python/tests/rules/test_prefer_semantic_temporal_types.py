from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING, Never

import pytest
from sarj_rule_contracts import Severity
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.prefer_semantic_temporal_types import PreferSemanticTemporalTypes


if TYPE_CHECKING:
    from sarj_python_lint._file_context import PythonFileContext


_HEADER = "from pydantic import BaseModel, Field\nclass Entry(BaseModel):\n"


def test_documented_examples() -> None:
    verify_native_rule(PreferSemanticTemporalTypes, analyze)


@pytest.mark.parametrize(
    ("field", "preferred"),
    [
        ("created_ms: int", "datetime"),
        ("expires_ms: int = 0", "AwareDatetime"),
        ("timestamp_seconds: float", "datetime"),
        ("ttl_seconds: int = 60", "timedelta"),
        ("duration_ms: float = 0", "timedelta"),
        ("timeout_seconds: float | None = None", "timedelta"),
    ],
)
def test_temporal_roles_remain_distinct(field: str, preferred: str) -> None:
    findings = PreferSemanticTemporalTypes().check(Path("app/models.py"), _HEADER + "    " + field + "\n")
    assert len(findings) == 1
    assert preferred in findings[0].message
    assert findings[0].severity is Severity.WARNING
    if preferred != "timedelta":
        assert "timedelta" not in findings[0].message


@pytest.mark.parametrize(
    "field",
    [
        "count: int = 0",
        "created: int",
        "size_ms: int",
        "elapsed_created_ms: int",
        "ttl_seconds: int = -1",
        "created_ms: str",
        "_created_ms: int",
        "created_ms: ClassVar[int] = 0",
        "ttl_seconds: timedelta",
        "created_ms: AwareDatetime",
    ],
)
def test_near_misses(field: str) -> None:
    source = (
        "from typing import ClassVar\nfrom datetime import timedelta\nfrom pydantic import AwareDatetime\n"
        + _HEADER
        + "    "
        + field
        + "\n"
    )
    assert PreferSemanticTemporalTypes().check(Path("app/models.py"), source) == []


@pytest.mark.parametrize(
    "source",
    [
        "class Entry:\n    created_ms: int\n",
        "def save(created_ms: int) -> None: pass\n",
        "from pydantic import BaseModel\nBaseModel = object\nclass Entry(BaseModel):\n    created_ms: int\n",
        "from pydantic import BaseModel\nclass Entry[BaseModel](BaseModel):\n    created_ms: int\n",
        "# Generated by protoc. Do not edit.\n" + _HEADER + "    created_ms: int\n",
        _HEADER + "    created_ms: int  # sarj-noqa: SARJ573 -- protocol requires integer epoch\n",
        "not python (",
    ],
)
def test_requires_model_semantics_and_respects_exclusions(source: str) -> None:
    assert PreferSemanticTemporalTypes().check(Path("app/models.py"), source) == []


def test_aliases_and_inherited_models() -> None:
    source = "import pydantic as pd\nclass Parent(pd.BaseModel): pass\nclass Entry(Parent):\n    expires_ms: int\n"
    assert len(PreferSemanticTemporalTypes().check(Path("app/models.py"), source)) == 1


def test_temporal_advice_supersedes_generic_numeric_advice(tmp_path: Path) -> None:
    path = tmp_path / "models.py"
    path.write_text(_HEADER + "    created_ms: int\n    count: int = 0\n")
    findings = analyze(["prefer-semantic-temporal-types", "prefer-typed-settings-field"], [path], root=tmp_path)
    assert [(finding.code, finding.line) for finding in findings] == [("SARJ573", 3), ("SARJ530", 4)]


@pytest.mark.parametrize(
    ("prefix", "decorator"),
    [
        ("from dataclasses import dataclass", "dataclass"),
        ("import dataclasses as dc", "dc.dataclass"),
        ("from pydantic.dataclasses import dataclass as value", "value"),
    ],
)
def test_dataclass_instants_have_semantic_types(prefix: str, decorator: str) -> None:
    source = prefix + "\n@" + decorator + "(frozen=True)\nclass Entry:\n    created_ms: int\n    expires_ms: int\n"
    findings = PreferSemanticTemporalTypes().check(Path("app/models.py"), source)
    assert len(findings) == 2
    assert all("datetime" in finding.message for finding in findings)


def test_temporal_suppression_retains_generic_numeric_warning(tmp_path: Path) -> None:
    path = tmp_path / "models.py"
    path.write_text(_HEADER + "    created_ms: int  # sarj-noqa: SARJ573 -- wire epoch required\n")
    findings = analyze(["prefer-semantic-temporal-types", "prefer-typed-settings-field"], [path], root=tmp_path)
    assert [finding.code for finding in findings] == ["SARJ530"]


def test_non_temporal_files_skip_project_semantic_index(monkeypatch: pytest.MonkeyPatch) -> None:
    def unexpected_index(_context: PythonFileContext) -> Never:
        pytest.fail("A file with no temporal field candidate built the project semantic index")

    monkeypatch.setattr(  # sarj-noqa: SARJ445 -- intercepts the semantic-index constructor to assert that non-temporal files skip it.
        "sarj_python_lint.rules.prefer_semantic_temporal_types.DeclaredContracts", unexpected_index
    )
    assert PreferSemanticTemporalTypes().check(Path("app/models.py"), _HEADER + "    count: int = 0\n") == []


@pytest.mark.parametrize(
    "source",
    [
        "from pydantic_settings import BaseSettings\nBaseSettings = object\nclass Entry(BaseSettings):\n    created_ms: int\n",
        "from pydantic_settings import BaseSettings\nclass Entry[BaseSettings](BaseSettings):\n    created_ms: int\n",
        "import pydantic_settings as ps\nps.BaseSettings = object\nclass Entry(ps.BaseSettings):\n    created_ms: int\n",
        "from pydantic_settings import BaseSettings\n@replacement\nclass Entry(BaseSettings):\n    created_ms: int\n",
    ],
)
def test_settings_require_stable_native_provider(source: str, tmp_path: Path) -> None:
    path = tmp_path / "models.py"
    path.write_text(source)
    assert analyze(["prefer-semantic-temporal-types"], [path], root=tmp_path) == []


