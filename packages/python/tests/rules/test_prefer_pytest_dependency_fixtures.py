@pytest.mark.parametrize(
    ("context", "header", "path", "prefix", "expected"), _CONTEXTS, ids=[case[0] for case in _CONTEXTS]
)
def test_dependency_fixture_contracts(
    *,
    rule: ProjectRule,
    allocation: str,
    body: str,
    context: str,
    header: str,
    path: str,
    prefix: str,
    expected: int,
) -> None:
    indent = "        " if context in {"method", "raises"} else "    "
