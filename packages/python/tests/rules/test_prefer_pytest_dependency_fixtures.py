from pathlib import Path

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.prefer_pytest_dependency_fixtures import PreferPytestDependencyFixtures


_SERVICE = "import pytest\nfrom typing import Protocol\nclass Port(Protocol):\n    def read(self): ...\nclass Store:\n    def read(self): return 1\nclass Service:\n    def __init__(self, store: Port):\n        self.store = store\n    def read(self): return self.store.read()\n"
_ALLOCATIONS = (
    ("inline", "service = Service(store=Store())"),
    ("local", "store = Store()\nservice = Service(store=store)"),
    ("positional", "store = Store()\nservice = Service(store)"),
    ("alias", "store = Store()\nalias = store\nservice = Service(alias)"),
    ("annotated", "store: Store = Store()\nservice = Service(store)"),
)
_CONTEXTS = (
    ("test", "def test_read():", "tests/test_service.py", "", 1),
    ("async", "async def test_read():", "tests/test_service.py", "", 1),
    (
        "parametrized",
        "@pytest.mark.parametrize('value', [1, 2])\ndef test_read(value):",
        "tests/test_service.py",
        "",
        1,
    ),
    ("method", "class TestRead:\n    def test_read(self):", "tests/test_service.py", "", 1),
    ("helper", "def make_service():", "tests/test_service.py", "", 0),
    ("fixture", "@pytest.fixture\ndef service():", "tests/test_service.py", "", 0),
    ("support", "def test_read():", "tests/fakes/test_service.py", "", 0),
    ("generated", "def test_read():", "tests/test_service.py", "# Generated by protoc. Do not edit.\n", 0),
    ("raises", "def test_read():\n    with pytest.raises(ValueError):", "tests/test_service.py", "", 0),
    ("application", "def test_read():", "app/service.py", "", 0),
)


@pytest.fixture
def rule() -> PreferPytestDependencyFixtures:
    return PreferPytestDependencyFixtures()


def test_documented_examples() -> None:
    verify_native_rule(PreferPytestDependencyFixtures, analyze)


@pytest.mark.parametrize(("allocation", "body"), _ALLOCATIONS, ids=[case[0] for case in _ALLOCATIONS])
@pytest.mark.parametrize(
    ("context", "header", "path", "prefix", "expected"), _CONTEXTS, ids=[case[0] for case in _CONTEXTS]
)
def test_dependency_fixture_contracts(
    *,
    rule: PreferPytestDependencyFixtures,
    allocation: str,
    body: str,
    context: str,
    header: str,
    path: str,
    prefix: str,
    expected: int,
) -> None:
    indent = "        " if context in {"method", "raises"} else "    "
    statements = f"{body}\nassert service.read() == 1".splitlines()
    indented = "".join(f"{indent}{line}\n" for line in statements)
    source = f"{prefix}{_SERVICE}{header}\n{indented}"
    assert len(rule.check(Path(path), source)) == expected, allocation


@pytest.mark.parametrize(
    "body",
    [
        "service = Service(store)\nassert service.read() == 1",
        "store = Store()\nassert store.read() == 1",
        "service = Service(make_store())\nassert service.read() == 1",
        "store = Store()\nstore = provided\nservice = Service(store)\nassert service.read() == 1",
    ],
)
def test_keeps_fixtures_factories_and_construction_under_test(rule: PreferPytestDependencyFixtures, body: str) -> None:
    source = (
        _SERVICE
        + "def test_read(store, provided, make_store):\n"
        + "".join("    " + line + "\n" for line in body.splitlines())
    )
    assert rule.check(Path("tests/test_service.py"), source) == []


def test_settings_dependency_is_a_fixture(rule: PreferPytestDependencyFixtures) -> None:
    source = "from pydantic_settings import BaseSettings\nclass Settings(BaseSettings):\n    enabled: bool = True\ndef test_call():\n    settings = Settings()\n    assert call(settings=settings)\n"
    assert len(rule.check(Path("tests/test_settings.py"), source)) == 1


@pytest.mark.parametrize(
    "header",
    [
        "@pytest.fixture\ndef test_factory():",
        "@custom\ndef test_read():",
        "class TestRead(Base):\n    def test_read(self):",
    ],
)
def test_fixture_decorators_and_inherited_contracts_are_not_collected_tests(
    rule: PreferPytestDependencyFixtures, header: str
) -> None:
    indent = "        " if header.startswith("class") else "    "
    source = (
        _SERVICE + header + "\n" + indent + "service = Service(Store())\n" + indent + "assert service.read() == 1\n"
    )
    assert rule.check(Path("tests/test_service.py"), source) == []
