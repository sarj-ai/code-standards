from __future__ import annotations

from pathlib import Path

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.prefer_explicit_class_contract import PreferExplicitClassContract


_BEHAVIOR = (
    "class Execution:\n"
    "    def __init__(self, client: AsyncClient, settings):\n"
    "        self.client = client\n"
    "        self.settings = settings\n"
    "        self.cancelled = False\n"
    "    async def run(self):\n"
    "        return await self.evaluate()\n"
    "    async def evaluate(self):\n"
    "        return await self.client.send(self.settings)\n"
)


def test_documented_examples() -> None:
    verify_native_rule(PreferExplicitClassContract, analyze)


@pytest.mark.parametrize("base", ["", "(object)"], ids=["implicit-object", "explicit-object"])
def test_state_and_behavior_need_an_explicit_contract(base: str) -> None:
    source = "from httpx import AsyncClient\n" + _BEHAVIOR.replace("class Execution:", f"class Execution{base}:")
    findings = PreferExplicitClassContract().check(Path("app/runner.py"), source)
    assert len(findings) == 1
    assert "Protocol" in findings[0].message
    assert "final" in findings[0].message


def test_annotated_collaborator_and_lifecycle_assignments_need_a_contract() -> None:
    source = "from httpx import AsyncClient\n" + _BEHAVIOR.replace(
        "self.client = client", "self.client: AsyncClient = client"
    ).replace("self.cancelled = False", "self.cancelled: bool = False")
    assert len(PreferExplicitClassContract().check(Path("app/runner.py"), source)) == 1


@pytest.mark.parametrize(
    "source",
    [
        "from typing import final\n@final\n" + _BEHAVIOR,
        "import typing as t\n@t.final\n" + _BEHAVIOR,
        _BEHAVIOR.replace("Execution:", "Execution(ExecutionPort):"),
        "from dataclasses import dataclass\n@dataclass\nclass Record:\n    value: int\n",
        "class Namespace:\n    LIMIT = 10\n",
        "class Utility:\n    def run(self):\n        return 42\n",
        "class Record:\n    value: int\n",
        "def factory():\n" + "\n".join("    " + line for line in _BEHAVIOR.splitlines()) + "\n",
        _BEHAVIOR.replace(
            "class Execution:",
            "class Execution:  # sarj-noqa: SARJ569 -- Framework registration owns the concrete class contract.",
        ),
        "invalid python !\n",
    ],
    ids=[
        "final",
        "qualified-final",
        "inherited-port",
        "dataclass",
        "namespace",
        "stateless",
        "data-record",
        "nested-factory",
        "external-contract-exception",
        "malformed",
    ],
)
def test_existing_contracts_records_and_utilities(source: str) -> None:
    assert PreferExplicitClassContract().check(Path("app/runner.py"), "from httpx import AsyncClient\n" + source) == []


def test_test_doubles_are_not_forced_to_add_a_base() -> None:
    assert (
        PreferExplicitClassContract().check(Path("tests/test_runner.py"), "from httpx import AsyncClient\n" + _BEHAVIOR)
        == []
    )


def test_configuration_only_extension_class_does_not_need_an_unused_base() -> None:
    source = (
        "class Generator:\n"
        "    def __init__(self, by_alias: bool, template: str):\n"
        "        self.by_alias = by_alias\n        self.template = template\n"
        "    def generate(self):\n        return self.template\n"
        "    def reference(self):\n        return self.by_alias\n"
    )
    assert PreferExplicitClassContract().check(Path("library/schema.py"), source) == []


def test_generated_header_precedes_imports_and_remains_excluded() -> None:
    source = "# Generated by protoc. Do not edit.\nfrom httpx import AsyncClient\n" + _BEHAVIOR
    assert PreferExplicitClassContract().check(Path("app/runner.py"), source) == []


def test_private_module_keeps_implementation_helpers_concrete() -> None:
    source = "from httpx import AsyncClient\n" + _BEHAVIOR
    assert len(PreferExplicitClassContract().check(Path("app/runner.py"), source)) == 1
    assert PreferExplicitClassContract().check(Path("app/_runner.py"), source) == []


def test_argument_only_record_with_an_external_value_is_not_an_execution_boundary() -> None:
    source = (
        "from compiler import TypeInfo\n"
        "class ModelField:\n"
        "    def __init__(self, name: str, info: TypeInfo):\n"
        "        self.name = name\n        self.info = info\n"
        "    def serialize(self):\n        return self.info.name\n"
        "    def to_argument(self):\n        return self.name\n"
    )
    assert PreferExplicitClassContract().check(Path("app/compiler.py"), source) == []
