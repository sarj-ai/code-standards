from pathlib import Path
from typing import TYPE_CHECKING

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.no_generic_json_parser import NoGenericJsonParser


if TYPE_CHECKING:
    from sarj_python_lint.rule_base import Rule


@pytest.fixture
def rule() -> Rule:
    return NoGenericJsonParser()


def test_documented_examples() -> None:
    verify_native_rule(NoGenericJsonParser, analyze)


@pytest.mark.parametrize(
    "source",
    [
        "from pydantic import TypeAdapter, JsonValue\nparser = TypeAdapter(dict[str, JsonValue])\n",
        "from pydantic import RootModel, JsonValue\nclass Response(RootModel[JsonValue]): pass\n",
        "from pydantic import TypeAdapter as Parser\nfrom typing import Any\nparser = Parser(type=dict[str, Any])\n",
        "import pydantic as p\ntype Payload = dict[str, p.JsonValue]\nparser = p.TypeAdapter(Payload)\n",
        "from pydantic import RootModel\nclass Response(RootModel[dict[str, object]]): pass\n",
    ],
)
def test_open_parsers(rule: Rule, source: str) -> None:
    assert len(rule.check(Path("tests/test_api.py"), source)) == 1


@pytest.mark.parametrize(
    "source",
    [
        "from pydantic import BaseModel, JsonValue\nclass Response(BaseModel):\n    metadata: JsonValue\n",
        "from pydantic import TypeAdapter\nparser = TypeAdapter(dict[str, int])\n",
        "from custom import TypeAdapter\nparser = TypeAdapter(dict[str, object])\n",
        "from pydantic import TypeAdapter, JsonValue\ndef make(TypeAdapter):\n    return TypeAdapter(JsonValue)\n",
        "from pydantic import TypeAdapter\nobject = Domain\nparser = TypeAdapter(dict[str, object])\n",
        "from pydantic import TypeAdapter, JsonValue\nparser = TypeAdapter(JsonValue)  # sarj-noqa: SARJ552 -- validates a schema-agnostic document transport\n",
        "# Generated by protoc. Do not edit.\nfrom pydantic import TypeAdapter, JsonValue\nparser = TypeAdapter(JsonValue)\n",
    ],
)
def test_models_domain_values_shadowing_and_exceptions(rule: Rule, source: str) -> None:
    assert rule.check(Path("app/parser.py"), source) == []


def test_recursive_alias_and_malformed_source_are_bounded(rule: Rule) -> None:
    source = "from pydantic import TypeAdapter\ntype First = Second\ntype Second = First\nparser = TypeAdapter(First)\n"
    assert rule.check(Path("app/parser.py"), source) == []
    assert rule.check(Path("app/parser.py"), "class Parser(:") == []
