from pathlib import Path

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.prefer_typed_settings_field import PreferTypedSettingsField


_PREFIX = "from enum import StrEnum\nfrom typing import NewType\nfrom pydantic import Field, PositiveInt, HttpUrl\nfrom pydantic_settings import BaseSettings\nclass Mode(StrEnum):\n    CLOUD = 'cloud'\nAccountId = NewType('AccountId', str)\n"
_FIELDS = (
    ("enum", "mode: str = Field(default=Mode.CLOUD)", 1),
    ("nominal", "account: str = AccountId('account')", 1),
    ("https", "endpoint: str = 'https://api.example.com'", 1),
    ("websocket", "endpoint: str | None = Field(default='wss://rtc.example.com')", 1),
    ("positive", "count: int = Field(default=1, gt=0)", 1),
    ("nonnegative", "delay: float = Field(default=0.0, ge=0)", 1),
    ("typed-enum", "mode: Mode = Mode.CLOUD", 0),
    ("plain", "label: str = 'deployment'", 0),
    ("typed-positive", "count: PositiveInt = 1", 0),
    ("required", "endpoint: str | None = Field(default=None)", 0),
)
_MODELS = (
    ("direct", "", "class Settings(BaseSettings):", 1),
    ("aliased", "import pydantic_settings as ps\n", "class Settings(ps.BaseSettings):", 1),
    ("inherited", "class Parent(BaseSettings): pass\n", "class Settings(Parent):", 1),
    ("plain", "", "class Settings:", 0),
    ("generated", "# Generated by protoc. Do not edit.\n", "class Settings(BaseSettings):", 0),
)


@pytest.fixture
def rule() -> PreferTypedSettingsField:
    return PreferTypedSettingsField()


def test_documented_examples() -> None:
    verify_native_rule(PreferTypedSettingsField, analyze)


@pytest.mark.parametrize(("field", "declaration", "actionable"), _FIELDS, ids=[case[0] for case in _FIELDS])
@pytest.mark.parametrize(("model", "prefix", "header", "checked"), _MODELS, ids=[case[0] for case in _MODELS])
def test_settings_domain_contracts(
    *,
    rule: PreferTypedSettingsField,
    field: str,
    declaration: str,
    actionable: int,
    model: str,
    prefix: str,
    header: str,
    checked: int,
) -> None:
    source = prefix + _PREFIX + header + "\n    " + declaration + "\n"
    assert len(rule.check(Path("app/settings.py"), source)) == actionable * checked, (field, model)


@pytest.mark.parametrize(
    "declaration",
    [
        "timeout: int = Field(default=10, gt=1)",
        "percentage: int = Field(default=1, ge=1, le=100)",
        "url: HttpUrl = 'https://api.example.com'",
        "port: int = 8000",
        "token: str = ''",
        "region: str = 'eu-west-1'",
    ],
)
def test_does_not_guess_domain_contracts_from_names(rule: PreferTypedSettingsField, declaration: str) -> None:
    source = _PREFIX + "class Settings(BaseSettings):\n    " + declaration + "\n"
    assert rule.check(Path("app/settings.py"), source) == []


def test_final_settings_class_keeps_its_domain_field_contract(rule: PreferTypedSettingsField) -> None:
    source = (
        "from typing import final\n"
        + _PREFIX
        + "@final\nclass Settings(BaseSettings):\n    count: int = Field(default=1, gt=0)\n"
    )
    assert len(rule.check(Path("app/settings.py"), source)) == 1


@pytest.mark.parametrize(
    ("prefix", "declaration"),
    [
        ("from typing import ClassVar\n", "endpoint: ClassVar[str] = 'https://api.example.com'"),
        ("from typing import ClassVar as Metadata\n", "mode: Metadata[str] = Mode.CLOUD"),
        ("import typing_extensions as te\n", "endpoint: 'te.ClassVar[str]' = 'https://api.example.com'"),
        ("from typing import Final\n", "endpoint: Final[str] = 'https://api.example.com'"),
        ("from typing import ClassVar\ntype Metadata = ClassVar[str]\n", "mode: Metadata = Mode.CLOUD"),
        ("", "_endpoint: str = 'https://api.example.com'"),
    ],
)
def test_settings_metadata_keeps_its_class_contract(
    rule: PreferTypedSettingsField, prefix: str, declaration: str
) -> None:
    source = prefix + _PREFIX + "class Settings(BaseSettings):\n    " + declaration + "\n"
    assert rule.check(Path("app/settings.py"), source) == []


def test_metadata_does_not_hide_an_ordinary_settings_field(rule: PreferTypedSettingsField) -> None:
    source = (
        "from typing import ClassVar\n"
        + _PREFIX
        + "class Settings(BaseSettings):\n"
        + "    kind: ClassVar[str] = 'https://metadata.example.com'\n"
        + "    endpoint: str = 'https://api.example.com'\n"
    )
    findings = rule.check(Path("app/settings.py"), source)
    assert len(findings) == 1
    assert findings[0].line == len(source.splitlines())


@pytest.mark.parametrize(
    ("prefix", "annotation", "default", "expected"),
    [
        ("def unrelated(str): ...\n", "str", "'https://api.example.com'", 1),
        ("def unrelated(Field): ...\n", "int", "Field(gt=0)", 1),
        ("from typing import Annotated, ClassVar\n", "Annotated[str, ClassVar[str]]", "'https://api.example.com'", 1),
        ("class str: pass\n", "str", "'https://api.example.com'", 0),
        ("", "str | None", "'https://api.example.com'", 1),
    ],
)
def test_settings_types_use_the_field_scope(
    rule: PreferTypedSettingsField, prefix: str, annotation: str, default: str, expected: int
) -> None:
    source = prefix + _PREFIX + f"class Settings(BaseSettings):\n    value: {annotation} = {default}\n"
    assert len(rule.check(Path("app/settings.py"), source)) == expected


def test_generic_type_parameter_is_not_a_primitive_settings_field(rule: PreferTypedSettingsField) -> None:
    source = _PREFIX + "class Settings[str](BaseSettings):\n    value: str = 'https://api.example.com'\n"
    assert rule.check(Path("app/settings.py"), source) == []


def test_unrelated_newtype_binding_does_not_hide_the_nominal_default(rule: PreferTypedSettingsField) -> None:
    source = (
        _PREFIX
        + "def unrelated(NewType): ...\n"
        + "class Settings(BaseSettings):\n    account: str = AccountId('account')\n"
    )
    [finding] = rule.check(Path("app/settings.py"), source)
    assert "AccountId" in finding.message


@pytest.mark.parametrize("replacement", ["AccountId = str", "def AccountId(value): return value"])
def test_rebound_nominal_factories_do_not_prove_a_domain_type(rule: PreferTypedSettingsField, replacement: str) -> None:
    source = _PREFIX + replacement + "\nclass Settings(BaseSettings):\n    account: str = AccountId('example')\n"
    assert rule.check(Path("app/settings.py"), source) == []
