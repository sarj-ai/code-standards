from pathlib import Path
from typing import TYPE_CHECKING

import pytest
from sarj_rule_contracts.examples import verify_native_rule

from sarj_python_lint.__main__ import analyze
from sarj_python_lint.rules.prefer_pytest_fixture_contract import PreferPytestFixtureContract


_CLASSES = "import pytest\nfrom abc import ABC, abstractmethod\nclass Store(ABC):\n    @abstractmethod\n    def read(self) -> int: ...\nclass SqlStore(Store):\n    def read(self) -> int: return 1\n    def explain(self) -> str: return 'query plan'\n"


if TYPE_CHECKING:
    from sarj_python_lint.rule_base import Rule


@pytest.fixture
def rule() -> Rule:
    return PreferPytestFixtureContract()


def test_documented_examples() -> None:
    verify_native_rule(PreferPytestFixtureContract, analyze)


@pytest.mark.parametrize(
    ("annotation", "body", "expected"),
    [
        ("SqlStore", "return SqlStore()", 1),
        ('"SqlStore"', "return SqlStore()", 1),
        ("Store", "return SqlStore()", 0),
        ("type[SqlStore]", "return SqlStore", 0),
        ("list[SqlStore]", "return [SqlStore()]", 0),
        ("SqlStore | None", "return SqlStore()", 0),
    ],
    ids=["concrete", "forward", "abstract", "factory", "collection", "union"],
)
def test_fixture_instance_annotation(rule: Rule, annotation: str, body: str, expected: int) -> None:
    source = _CLASSES + f"@pytest.fixture\ndef store() -> {annotation}:\n    {body}\n"
    assert len(rule.check(Path("tests/conftest.py"), source)) == expected


@pytest.mark.parametrize("wrapper", ["Iterator", "AsyncIterator", "Generator", "AsyncGenerator"])
def test_yield_fixture_contract(rule: Rule, wrapper: str) -> None:
    source = (
        _CLASSES
        + f"from collections.abc import {wrapper}\n@pytest.fixture\ndef store() -> {wrapper}[SqlStore]:\n    yield SqlStore()\n"
    )
    assert len(rule.check(Path("tests/conftest.py"), source)) == 1


@pytest.mark.parametrize("member", ["read", "explain"])
def test_implementation_specific_local_consumers_keep_concrete_contract(rule: Rule, member: str) -> None:
    source = (
        _CLASSES
        + f"@pytest.fixture\ndef store() -> SqlStore:\n    return SqlStore()\ndef test_read(store: SqlStore):\n    assert store.{member}()\n"
    )
    assert len(rule.check(Path("tests/test_store.py"), source)) == (1 if member == "read" else 0)


def test_protocol_contract_and_renamed_fixture(rule: Rule) -> None:
    source = "import pytest\nfrom typing import Protocol\nclass Store(Protocol):\n    def read(self) -> int: ...\nclass SqlStore(Store):\n    def read(self) -> int: return 1\n@pytest.fixture(name='store')\ndef sql_store() -> SqlStore:\n    return SqlStore()\n"
    assert len(rule.check(Path("tests/conftest.py"), source)) == 1


@pytest.mark.parametrize(
    "replacement",
    [
        "def store() -> SqlStore:",
        "@custom\ndef store() -> SqlStore:",
        "@pytest.fixture\ndef store() -> Unknown:",
        "@pytest.fixture\ndef store() -> Store:",
    ],
)
def test_unresolved_and_nonfixture_contracts(rule: Rule, replacement: str) -> None:
    source = _CLASSES + replacement + "\n    return SqlStore()\n"
    assert rule.check(Path("tests/conftest.py"), source) == []


def test_plain_abc_without_abstract_members_is_not_a_service_contract(rule: Rule) -> None:
    source = (
        _CLASSES.replace("    @abstractmethod\n", "")
        + "@pytest.fixture\ndef store() -> SqlStore:\n    return SqlStore()\n"
    )
    assert rule.check(Path("tests/conftest.py"), source) == []


def test_fixture_retains_its_inherited_abstract_contract(rule: Rule) -> None:
    source = "import pytest\nfrom abc import ABC, abstractmethod\nclass Store(ABC):\n    @abstractmethod\n    def read(self) -> int: ...\nclass SpecializedStore(Store): pass\nclass SqlStore(SpecializedStore):\n    def read(self) -> int: return 1\n@pytest.fixture\ndef store() -> SpecializedStore:\n    return SqlStore()\n"
    assert rule.check(Path("tests/conftest.py"), source) == []


def test_concrete_fixture_uses_the_nearest_inherited_abstract_contract(rule: Rule) -> None:
    source = "import pytest\nfrom abc import ABC, abstractmethod\nclass Store(ABC):\n    @abstractmethod\n    def read(self) -> int: ...\nclass SpecializedStore(Store): pass\nclass SqlStore(SpecializedStore):\n    def read(self) -> int: return 1\n@pytest.fixture\ndef store() -> SqlStore:\n    return SqlStore()\n"
    [finding] = rule.check(Path("tests/conftest.py"), source)
    assert "`SpecializedStore` contract" in finding.message


def test_fixture_contract_suppression_and_generated_source(rule: Rule) -> None:
    source = (
        _CLASSES
        + "@pytest.fixture\ndef store() -> SqlStore:  # sarj-noqa: SARJ550 -- this fixture exposes SQL implementation hooks\n    return SqlStore()\n"
    )
    assert rule.check(Path("tests/conftest.py"), source) == []
    generated = "# Generated by protoc. Do not edit.\n" + source.replace(
        "  # sarj-noqa: SARJ550 -- this fixture exposes SQL implementation hooks", ""
    )
    assert rule.check(Path("tests/conftest.py"), generated) == []
    assert rule.check(Path("tests/conftest.py"), "def fixture(:") == []
