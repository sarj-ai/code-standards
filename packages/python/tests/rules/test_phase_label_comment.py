from pathlib import Path
from textwrap import dedent
from typing import TYPE_CHECKING

import pytest

from sarj_python_lint.rules.phase_label_comment import TestPhaseLabelComment


if TYPE_CHECKING:
    from sarj_python_lint.rule_base import Diagnostic


def _check(source: str, path: str = "tests/test_thing.py") -> list[Diagnostic]:
    return TestPhaseLabelComment().check(Path(path), dedent(source))


LABELS = [
    "given",
    "when",
    "then",
    "Arrange",
    "Act",
    "Assert",
    "Assertions",
    "ASSERTION",
    "Verify",
    "Verification",
    "Exercise",
    "Execute",
    "Cleanup",
    "Prepare",
    "Sanity check",
    "Arrange / Act",
    "Act/Assert",
    "given / when",
    "When/Then",
    "Then:",
    "act.",
    "Assert -",
]


@pytest.mark.parametrize("label", LABELS)
def test_flags_a_bare_phase_label(label: str) -> None:
    diags = _check(f"""
        def test_it():
            # {label}
            assert works()
        """)
    assert len(diags) == 1
    assert diags[0].code == "SARJ089"


def test_a_phase_word_carrying_a_sentence_is_left_alone() -> None:
    """`# then the retry loop spins forever` is a why, not a signpost."""
    diags = _check("""
        def test_it():
            # then the retry loop would spin forever
            assert works()
        """)
    assert diags == []


def test_setup_and_teardown_belong_to_sarj016() -> None:
    """SARJ016 owns those two through its section-label vocabulary; one deletion, one finding."""
    diags = _check("""
        def test_it():
            # Setup
            client = make()
            # Teardown
            client.close()
        """)
    assert diags == []


def test_a_trailing_comment_is_not_a_phase_label() -> None:
    """A phase label owns its line; `x = 1  # act` is annotating the value."""
    diags = _check("""
        def test_it():
            result = act()  # act
            assert result
        """)
    assert diags == []


def test_a_label_inside_a_bracketed_expression_is_left_alone() -> None:
    """At bracket depth the word is labelling an element of the literal, not a phase."""
    diags = _check("""
        def test_it():
            cases = [
                # given
                ("a", 1),
            ]
            assert cases
        """)
    assert diags == []


def test_a_non_test_file_is_left_alone() -> None:
    diags = _check(
        """
        def run():
            # then
            return 1
        """,
        path="src/app/pipeline.py",
    )
    assert diags == []


def test_generated_files_are_exempt() -> None:
    diags = _check("""
        # Code generated by a tool. DO NOT EDIT.
        def test_it():
            # given
            assert works()
        """)
    assert diags == []


def test_a_word_merely_starting_with_a_phase_word_is_left_alone() -> None:
    diags = _check("""
        def test_it():
            # actor
            assert works()
        """)
    assert diags == []


def test_reports_every_label_in_source_order() -> None:
    diags = _check("""
        def test_it():
            # given
            a = 1
            # when
            b = f(a)
            # then
            assert b
        """)
    assert [d.line for d in diags] == [3, 5, 7]
    assert {d.col for d in diags} == {5}


def test_an_unparseable_file_reports_nothing() -> None:
    assert _check("def test_it(:\n    # given\n") == []
