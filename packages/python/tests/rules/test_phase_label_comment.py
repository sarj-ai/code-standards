_PUBLIC_EXAMPLES = TestPhaseLabelComment.public_examples()


@pytest.mark.parametrize("example", _PUBLIC_EXAMPLES, ids=tuple(e.example_id for e in _PUBLIC_EXAMPLES))
def test_public_documentation_examples_are_executable(example: RuleExample) -> None:
    focus = example.focus_file
    assert len(TestPhaseLabelComment().check(Path(focus.path), focus.source)) == example.expected_count


@pytest.mark.parametrize("label", LABELS)
def test_flags_a_bare_phase_label(label: str) -> None:
    diags = _check(f"""
        def test_it():
            # {label}
            assert works()
        """)
    assert len(diags) == 1
    assert diags[0].code == "SARJ089"
    assert diags[0].severity is Severity.WARNING
    assert label in diags[0].message


def test_a_phase_word_carrying_a_sentence_is_left_alone() -> None:
    diags = _check("""
        def test_it():
            # then the retry loop would spin forever
            assert works()
        """)
    assert diags == []


def test_setup_and_teardown_belong_to_sarj016() -> None:
    diags = _check("""
        def test_it():
            # Setup
            client = make()
            # Teardown
            client.close()
        """)
    assert diags == []


