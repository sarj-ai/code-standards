@pytest.mark.parametrize(
    "comment",
    [
        "----",
        "then?",
        "Act II",
        "Arrange / Act / Assert the result",
        "Given / When / Therefore",
        f"{'-' * 41} Arrange",
        "-*- coding: utf-8 -*-",
    ],
)
def test_decoration_and_joins_do_not_hide_non_phase_content(comment: str) -> None:
    diags = _check(f"""
        def test_it():
            # {comment}
            assert works()
        """)

    assert diags == []


def test_reports_every_label_in_source_order() -> None:
    diags = _check("""
        def test_it():
            # given
            a = 1
            # when
            b = f(a)
            # then
            assert b
        """)
    assert [d.line for d in diags] == [3, 5, 7]
    assert {d.col for d in diags} == {5}


def test_an_unparseable_file_reports_nothing() -> None:
    assert _check("def test_it(:\n    # given\n") == []


@pytest.mark.parametrize("source", ["def test_it()\n    # Arrange\n    pass\n", "x = (1 2)\n# Arrange\n"])
def test_tokenizable_but_invalid_python_reports_nothing(source: str) -> None:
    assert _check(source) == []
