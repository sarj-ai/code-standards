#!/usr/bin/env node
// Write src/index.ts from the rule files in src/rules/ and src/docs/index.ts
// from the documentation files in src/docs/ (files starting with "_" are
// private helpers). Run after adding or removing a rule.

import { readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { PACKAGE_DIR } from "./lib.ts";

await main();

async function main(): Promise<void> {
  const rules = await modules("src/rules");
  const docs = await modules("src/docs");
  const undocumented = rules.filter((rule) => !docs.includes(rule));
  const orphaned = docs.filter((doc) => !rules.includes(doc));
  if (undocumented.length > 0 || orphaned.length > 0) {
    throw new Error(`every rule needs src/docs/<rule>.ts and every docs module a rule: undocumented [${undocumented.join(", ")}], orphaned [${orphaned.join(", ")}]`);
  }
  await writeFile(join(PACKAGE_DIR, "src/index.ts"), [
    "/**",
    " * @fileoverview index — the @sarj rules written for Oxlint's plugin API.",
    " *",
    " * Each rule sets up once per run with `createOnce` and resets per-file state in",
    " * `before`. Nothing here imports `eslint` or `@typescript-eslint/*`.",
    " * Generated by scripts/oxlint/generate-index.ts; do not edit by hand.",
    " */",
    "",
    'import type { Plugin } from "@oxlint/plugins";',
    "",
    ...rules.map((rule) => `import ${ident(rule)} from "./rules/${rule}.js";`),
    "",
    "const RULES = {",
    ...rules.map((rule) => `  ${JSON.stringify(rule)}: ${ident(rule)},`),
    "};",
    "",
    "const PLUGIN = {",
    '  meta: { name: "@sarj" },',
    "  rules: RULES,",
    "} satisfies Plugin;",
    "",
    "export default PLUGIN;",
    "",
  ].join("\n"));
  await writeFile(join(PACKAGE_DIR, "src/docs/index.ts"), [
    "/**",
    " * @fileoverview docs — every rule's documentation and executable examples, by rule name.",
    " *",
    " * Generated by scripts/oxlint/generate-index.ts; do not edit by hand.",
    " */",
    "",
    ...docs.map((doc) => `import { ${constant(doc)} } from "./${doc}.js";`),
    "",
    "export const RULE_DOCUMENTATION = {",
    ...docs.map((doc) => `  ${JSON.stringify(doc)}: ${constant(doc)},`),
    "} as const;",
    "",
  ].join("\n"));
  console.log(`${String(rules.length)} rules`);
}

async function modules(directory: string): Promise<string[]> {
  return (await readdir(join(PACKAGE_DIR, directory)))
    .filter((file) => file.endsWith(".ts") && !file.startsWith("_") && file !== "index.ts")
    .map((file) => file.slice(0, -3))
    .sort();
}

function ident(name: string): string {
  return name.replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase()).replace(/^(\d)/, "_$1");
}

function constant(name: string): string {
  return `${name.toUpperCase().replaceAll("-", "_")}_DOCUMENTATION`;
}
